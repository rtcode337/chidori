  #
  # 「<県>の食文化」「<県>の菓子」は単独では入れない。食文化は企業・番組・人物・動植物まで
  # 抱えていて（前の作り方で 1,007 件のうち 6 割を落とした）、菓子はかき氷・鰹節のような
