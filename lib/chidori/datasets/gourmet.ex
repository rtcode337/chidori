    """
  end

  # 代表店を決める段。`retry` は代表店なしを探し直すのがどこか
  defp shop_step(n, retry) do
    """
    **#{n}. 代表店の決まっていない料理に、代表店を決める。** tags に "#{@unplaced_tag}" が
    付いた料理です（`extra.shop` がまだ無いものと、前に書いた手がかりで辞典の店に
    引き当てられなかったもの）。**料理は 1 回に 20 品まで**で構いません（残りは次の回に、
    この県のまま続きから頼みます）。**店の 1 件はこの数に数えず、この県の店は全部片付けて
    ください**（代表店がその店自身なので、調べることが少ない）。
    上の一覧に「〔shop: 引き当てられなかった —— 理由（手がかり: …）〕」と添えられている料理は、
    前に書いた手がかりで辞典の店に引き当てられなかったものです。理由を読んで、
    **正式な店名（看板どおり）と、都道府県から番地までの住所**を書き直すか、別の店を選んでください。
    **同じ手がかりをもう一度書いても、同じ理由で落ちます。**
    **店の 1 件**（tags に "#{@shop_tag}"）の代表店は**その店自身**です（下の「店の 1 件」）。
    **web で調べても、いまその料理を確実に食べられる・買える店が見つからなかったら**、
    代表店なしとして返してください: `extra.shop` に null、tags に "#{@no_shop_tag}"、
    `extra.#{@no_shop_key}` に理由を 1 行（何を調べて何が無かったか。例「県と観光協会の紹介に
    提供店が無く、最後の提供店は 2021 年に閉店」）、`extra.checked_on` に今日の日付。
    **代表店なしは、調べたうえで無かったときだけです。** 「調べきれていない」「時間が足りない」
    なら代表店なしにせず、その料理は返さずに代表店未定のまま残してください（次の回が続きを調べます）。
    **料理そのものが終わった証拠**（どこでも出さなくなった・イベントの終了・団体の解散・
    期間限定の店や販売の終了・「現在販売は行っていません」）が見つかったときは、代表店なしでは
    なく墓標で消してください（下の「終わったもの」）。
    "#{@no_shop_tag}" の付いた料理は、ここでは探し直さないでください（#{retry}）。

    #{shop_rule()}
    """
  end

