    """
  end

  # 何をご当地グルメに入れるか。**2 つの依頼文で同じ文を使う** —— 書き分けると、
  # 片方の回が足したものをもう片方の回が消す
  defp scope_rule do
    """
    **入れるもの・入れないもの**

    - **入れる** …… その土地の名で知られる料理・郷土料理・ご当地の麺や丼・郷土菓子・
      土産菓子・駅弁・土地と食材の組（「大間のマグロ」「関あじ」）。食べられる店でも、
      **買える店でもかまいません**（市場・直売所・駅の売店・土産物店も可）。
      **店は、料理と結び付く 3 つだけ**入れます（発祥の店・名物の店・チェーンの本店。下の「店の 1 件」）
    - **入れない** …… どこにでもある料理（カツ丼・おでん・素麺のような一般名）、
      この県の名物と言えない一般名の食材（下の「一般名の食材」の決まり）、
      会社・メーカーそのもの（訪ねる店を持たない製菓会社・食品会社）、
      **全国チェーンそのもの**（本店がその土地の名物として訪ねる先になっていないもの）、
      即席麺のような全国で売る商品、
      イベント・団体・番組・マスコット、一覧や総称（「◯◯三大麺」）、**米の品種・銘柄米**
      （スーパーで買えるものがほとんどで、行き先が決まらない。名簿に混ざっていたら墓標で消す）、
      **もう終わったもの**
    - **県は受け持ちの県だけ**です（タグ "#{area_tag()}:<県>" はこの県の 1 つ）。
      **広い地域にまたがる料理は 1 件・1 県**（発祥か本場の県）にします。
      **発祥を 2 つ以上の県が主張している料理**（ソースカツ丼など）は県ごとに 1 件ずつで、
      見出しの後ろに「（県名）」を付けます（見出しは一覧の中で 1 つしか持てないため）

    #{generic_food_rule()}
    """
  end

  # 一般名の食材（「スダチ」「ユズ」のように土地の名が付かない作物）の決め方。**地名の有無では
  # 分けない** —— ほぼ一つの県でしか作られない作物は、地名を付ける必要が無かったので名前に
  # 土地が入らない（スダチ・シークヮーサー）。名簿の確かめ（ざっと見る・情報収集）と足すとき（情報収集）で同じ文を使う
  defp generic_food_rule do
    """
    **一般名の食材**（「スダチ」「ユズ」「サトウキビ」のように、名前に土地の名が付かない作物・魚介）は、
    次のどちらかに当てはまるときだけ残してください: **この県が全国でずば抜けた産地**（収穫量の大半を
    占める・発祥の地）、または**県や市町村が名物として売り出している**（その頁を `extra.sources` に）。
    残すものは `extra.#{@display_key}` に「徳島のスダチ」のように**土地を頭に付けた名前**を書きます。
    当てはまらないもの（ユズのように各地にあるもの、サトウキビのように作物そのもので訪ねた人が
    そのまま食べるものでないもの）は、理由を書いて墓標で消してください
    """
  end

  # 店の 1 件の決め方（利用者の決めごと: 主役は料理。店はご当地グルメの発祥の店・ご当地グルメの
  # 名物の店（この 2 つは地図にグルメ名で出す）・有名なチェーンの本店（それ自体が名物）だけで、
  # 古い・有名というだけの店は入れない）。
  # **2 つの依頼文で同じ文を使う**。料理と店の重なり（同じ店を指す料理と店）もここで決める ——
  # 同じ店にピンが 2 本立つと、地図ではどちらを押しても同じ店で、数だけが水増しされる。
  # **残すのはいつも料理**（利用者の決めごと。スポット名 = 料理名で、店名は説明の代表店の行で出る）。
  # 提供店が 1 軒の料理でも料理を残す —— 地図で探すのは「その土地で何を食べるか」で、
  # 店名だけのピンでは何を出す店か読めない。書き出しの `without_same_shop/1` も同じ向き。
  #
  # 発祥の店・名物の店は、店の 1 件の `extra.display_name` にグルメ名を書かせる（地図はグルメ名で
  # 出し、店名は説明の「店: …」の行で出る）。発祥の店は料理名そのまま（発祥店のカテゴリと説明で
  # 発祥だと読める）で、同じ料理の発祥を名乗る店が別にある・同じ名前の料理の 1 件が別の県にある
  # ときだけ土地を頭に付ける。名物の店は発祥ではないので、いつも土地を頭に付ける（一般名の食材の
  # 「徳島のスダチ」と同じ付け方）。名前だけ見て発祥の店だと読まれないように
  defp shop_item_rule do
    """
    **店の 1 件**（tags に "#{@shop_tag}"）

    ご当地グルメの地図なので、**主役は店ではなく料理（グルメ）です**。

    - **入れる店は次の 3 つだけです。** どれに当たるかをタグ "#{@shop_why}:<語>" で付けてください
      （語は #{Enum.map_join(@shop_whys, " / ", &~s("#{&1}"))} のどれか）
      1. **発祥の店** …… その土地のグルメ（料理・菓子・パン・飲み物など）の**発祥・元祖とされる店**で、
         いまもそれを出している（売っている）。タグ "#{@origin_tag}" も付けます
      2. **名物の店** …… 発祥ではないが、**その土地のグルメを食べられる・買える店として広く知られた店**
         （県・市区町村・観光協会がそのグルメの店として紹介している、百科事典の記事にそのグルメの店として
         書かれている）
      3. **チェーンの本店** …… **有名なチェーンの本店**（チェーンそのものがその土地の名物として知られ、
         本店が訪ねる先になっているもの）

      どれも、**地元で十分に知られていること**が前提です。目安は**百科事典に記事がある**か、
      **県・市区町村・観光協会がその土地の名物の店として紹介している**こと
    - **1 と 2 は地図にグルメ名で出します。** `extra.#{@display_key}` に**そのグルメの名前**を書いてください
      （店名は説明の「店: …」の行に出ます）。1 は**料理名そのまま**です —— **同じ料理の発祥を名乗る店が
      別にある**ときと、**同じ名前の料理の 1 件が別の県にある**ときだけ、店のある土地を頭に付けます。
      2 は発祥ではないので、**いつも店のある土地を頭に付けます**（「浜松のうなぎ」のように、市区町村か
      よく知られた地区の名前）。3 は店名のまま（`extra.#{@display_key}` は書かない）
    - **入れない店**（名簿に入っていたら理由を書いて墓標）……
      **古い・有名というだけで、結び付くご当地グルメを挙げられない店**（老舗の料亭・名店でも、
      その店が発祥の店・名物の店として知られるグルメが無いもの。理由は「ご当地グルメと結び付かない店」）、
      **地元でも知られていない店**、**本店（発祥の店）が決まらないチェーン**、
      **全国チェーンそのもの**（本店が名物として訪ねる先になっていない）、**閉店した店**
      （チェーンなら本店が閉じて、ほかに発祥の店も残っていないとき）、
      料理を出さない店（お酒だけのバー・クラブ）、記事が施設や会社のことを書いていて
      店として訪ねられないもの
    - **"#{@shop_why}:" の付いていない店の 1 件は、前の決まりで入ったものです**（前は、地元で知られた店なら
      老舗というだけでも入れていました）。**この回で 3 つのどれに当たるかを調べ直してください。**
      当たればタグと `extra.#{@display_key}`（1 と 2）を付けて返し、`extra.#{@shop_reason_key}` も
      その理由に書き直します（例: 老舗のパン屋として入っていた店が、その土地で食パンの発祥とされて
      いるなら、1 として `extra.#{@display_key}` を「食パン」にし、理由に発祥とされることを書く）。
      **どれにも当たらないと分かったら**、「ご当地グルメと結び付かない店」と書いて墓標で消してください
    - **消すのは、消す理由を確かめたときだけ**です —— どれにも当たらないと確かめたときか、
      ほかの消す理由（閉店の告知・訪ねる店を持たない会社・屋号の総称だと分かる頁）を確かめたとき。
      「記事が運営会社のことを書いている」だけでは消さないでください —— 本店・発祥の店・旗艦店を
      訪ねられるなら店の 1 件として 3 つのどれかを
      確かめ、代表店をその店にしてください（ラーメンやつけ麺の名店が会社として記事になっていることは
      よくあります）。**調べきれなければ消さずに、"#{@shop_why}:" を付けないまま返さずに残してください**
      （次の回が続きを調べます）。代表店が決まらなければ代表店未定のままで構いません
    - title は**店名**（百科事典の記事名か、看板どおりの名前。支店名は付けない ——
      「ラーメン二郎 三田本店」ではなく「ラーメン二郎」）。**見出しは変えないでください**
      （地図に出す名前は `extra.#{@display_key}`）
    - 代表店（`extra.shop`）は**その店自身**です。チェーン・暖簾分けで店が何軒もあるなら
      **本店**（無ければ発祥の店・いちばん古い店）。タグ "代表店:本店"（1 軒だけの店も
      "代表店:本店"）、発祥・元祖の店なら（3 のチェーンの本店でも）"#{@origin_tag}" も。
      "提供店:<店の数>" はその店の軒数（1 軒だけなら 1）
    - "#{genre_tag()}:<種類>" は**その店の主な料理の種類**（料亭・天ぷら・割烹は 和食、
      洋食屋・中華料理店は 洋食・中華、喫茶店は 飲み物）。1 と 2 は**そのグルメの種類**
    - **料理の 1 件が上の一覧に既にあるときは、1 と 2 ではなく次の「料理と店の重なり」に従ってください**
    - **料理と店の重なり**: 料理の 1 件と店の 1 件が**同じ店を指す**とき（料理の代表店がその店か、
      その店が料理の発祥・本店で、いまもその料理を出している。二郎系ラーメンとラーメン二郎、
      家系ラーメンと吉村家など）は、**同じ店にピンが 2 本立たないように**します。
      **残すのはいつも料理です**（"提供店:1" で、ほぼその店でしか食べられない料理でも同じ）——
      - **料理を残し**、料理の代表店をその店にして（発祥・元祖の店なら "#{@origin_tag}" も）、
        `extra.#{@shop_reason_key}` にその店を選んだ理由を書く
      - **店の 1 件は「<料理>の 1 件にまとめた（代表店）」と書いて墓標**で消す
        （発祥の店なら「<料理>の 1 件にまとめた（代表店・発祥店）」）
      - 情報収集の回で料理の 1 件が上にあるなら、その店の 1 件は足さないでください
      - 料理の代表店が別の店（その店が閉じた・料理を出していない）なら、両方残してよい
      - **消す前に、料理の 1 件が上に生きていることを確かめてください**（両方消すと、どこにも残りません）
    """
  end

  # 代表店の決め方（利用者の決めごと）。**2 つの依頼文で同じ文を使う**
  defp shop_rule do
    """
    **代表店の決め方**（上から順に当ててください）

    1. **本店**があれば本店（チェーンや暖簾分けで広まった料理・菓子） → タグ "代表店:本店"
    2. 無ければ**とりわけ有名な店**（公的な紹介・取材・行列で名前が挙がる店） → "代表店:有名店"
    3. どちらも無ければ**行きやすい店**（駅や観光の中心から近く、いつも出している・売っている店。
       土産や駅弁なら駅や空港の売店・直営店、食材なら市場・直売所・それを出す食堂） → "代表店:行きやすい店"

    - **その品を看板にしている店を選んでください。** 産地の直売所、生産者・組合・製造元の直営店、
      その料理を看板に出している店（茶なら茶園・茶業の直売所、果物なら農園の直売所、菓子なら製造元の店）が
      あれば、そちらが先です。**アンテナショップ・物産館・百貨店・駅や空港の総合の土産店・道の駅の
      フードコートのように、いろいろな品を並べる店は、その品を少し置いているだけのことが多いので、
      ほかに買える・食べられる店が無いときだけ**にしてください（その品を主に扱っていると、売り場や
      品ぞろえの紹介で確かめたときに限る）。**産地の外の店も同じで、産地や発祥の町に店があればそちら**を
      選びます（県の外でもよいのは、本店がそこにあるときです）

    - **いまその料理を出している（売っている）と確かめた店だけ**にしてください
      （公式のメニュー・直近 1 年ほどの告知や紹介で）
    - 代表店は**料理の県の外でもかまいません**（本店が東京にある、など）
    - **発祥・元祖とされる店が、いまも営業していてその料理を出しているなら**、タグ "#{@origin_tag}" を
      付けてください（代表店がその店のときだけ。発祥店でも本店を先に選びます）
    - 書くのは `extra.shop` の `name`（看板どおりの店名）・`address`（都道府県から番地まで）・
      `url`（その店の公式の頁か、その店を紹介している公的な頁）と `ref`。
      **`ref` は手がかりを書く前に引いてください**: chiezo の MCP で地図辞典 osm_japan・店舗辞典
      overture_japan をその店名で引き（search か titles。「本店」や支店名を外した名前でも引く）、
      住所の合う見出しを `osm_japan:見出し` の形で書きます。**百科事典の記事名と辞典の見出しは
      書き方が違うことが多く**（ひらがなと漢字・空白・店名の後ろの「本店」など）、名前だけだと
      「辞典に同じ名前がありません」で落ちます。どちらの辞典にも無ければ `ref` は書かず、
      **住所を店の公式の頁などで確かめて番地まで正確に**書いてください（店の辞典に無い店は、
      住所から座標を引きます。番地まで合わないと地図に置けません）
    - **座標（lat / lon）は、辞典にも住所にも当たらない店に限って**、地図サービスで確かめた値を
      書いてください（記憶で書かない）。辞典に当たれば辞典の座標を使います
    - 代表店を書いたら、**その店を選んだ理由を `extra.#{@shop_reason_key}` に 1 行で**書いてください
      （例「1950 年創業で、この料理の発祥とされる店。いまも本店で出している」「県の観光協会が
      この料理の店として紹介している」）。**確かめた頁に書いてある事実だけ**（創業の年・発祥や本店で
      あること・公的な紹介・駅からの近さ）で、**口コミの評点や「美味しい」「人気」のような感想は
      書かないでください**。店の 1 件では、その店をご当地グルメに入れた理由を書きます。
      代表店を null にしたときは `extra.#{@shop_reason_key}` も null
    - **代表店が閉店した・その料理をやめた**ときは、料理は消さずに、上の決まりで店を選び直して
      `extra.shop` を書き直してください。探しても選び直せなければ、`"shop": null` にして
      tags に "#{@no_shop_tag}"、`extra.#{@no_shop_key}` に理由を書いてください（代表店なし）
    """
  end

  # 終わったものの扱い（利用者の決めごと: 地図から消し、理由は Chiezo に残す）
  defp ending_rule do
    """
    **終わったものは墓標で消してください**（tags に "#{Chiezo.tombstone_tag()}"、body に
    「2019 年に実行委員会が解散」のように理由を 1 行）。期間限定の店・販売が終わったもの
    （「◯年◯月までの期間限定」「現在販売は行っていません」。復活に向けて試作中でも、いま
    手に入らないなら終わり）も終わったものです。代表店なしにはしないでください。**消すのは終わった証拠が見つかった
    ときだけ**です（見つからないだけでは消さない）。代表店の閉店は料理の終わりではないので、
    消さずに代表店を選び直してください。**店の 1 件は、その店の閉店が終わり**です
    （チェーンの本店だけが閉じて、ほかの店が続いているなら、発祥の店・いちばん古い店に選び直す）。
    **tags に "#{Chiezo.locked_tag()}" が付いた料理は、人が現地で位置を確かめたものです。**
    墓標にすると消えずに "#{@doubt_tag}" が付いて残ります（"#{@doubt_tag}" は消さないでください）。
    """
  end

  # 1 件の形。**2 つの依頼文で同じものを使う**（travel-log が読むのはこの形）。
  # 脇書きの鍵は Chiezo の上限（1 件 20 鍵。Chiezo の印を含む）に収まるよう、AI に書かせる
  # 10 こ（shop・available_months・season_note・opening_hours・municipality・sources・checked_on・
  # no_shop・display_name・shop_reason）だけにしてある。機械が運ぶ lat・lon・url・pageviews_month と Chiezo の印
  # （消した理由・見直した印など）を足しても 20 に届かない（足すなら、どれかを減らしてから）
  defp item_format do
    """
    **1 件の形**

    - title: **料理の名前だけ**（その土地で通っている呼び名。百科事典に記事があれば記事名に
      揃える。土地と食材の組は「大間のマグロ」のように土地を頭に。店の 1 件は店名）。**丸かっこの補足は付けない**
      （発祥を争う料理の「（県名）」だけ）。**同じ料理は同じ表記で**返してください —— ここが
      同一の鍵で、上に並んでいるものはその表記のまま返します
    - body: **2〜3 文の説明を自分の言葉で**（何で・どこで・いつ食べるものか）。百科事典や
      口コミの文を写さないでください
    - url: いちばん確かな出典 1 つ（県・市区町村・観光協会・農林水産省の紹介、代表店の公式の頁、
      百科事典の記事）。**実際に開いて確かめたものだけ**
    - tags: **いま付いているタグは、直すもの以外そのまま残してください**（返した内容で丸ごと
      置き換わるので、書かなかったタグは消えます）
      - "#{kind_tag()}" —— この一覧の目印。**必ず付けてください**
      - "#{area_tag()}:<県>" —— 受け持ちの県。**変えないでください**（受け持つ県が
        「#{@unknown_region}」の回だけ、本店のある県に付け替えます）
      - "#{@shop_tag}" —— **店の 1 件だけ**（料理の 1 件には付けない）
      - "#{genre_tag()}:<種類>" —— 1 つだけ、次の語から: #{Enum.join(@kinds, " / ")}
        （果物 —— みかん・梨・ぶどう・いちご・メロンなど —— は "フルーツ"、野菜・米以外の穀物・
        魚介・肉・茶の産地は "食材"。焼きそばは "麺類"）
      - "代表店:本店" / "代表店:有名店" / "代表店:行きやすい店" —— 代表店を選んだ決まり（代表店があるとき）
      - "#{@no_shop_tag}" —— 調べたが代表店が見つからなかったとき（`extra.shop` は null、理由は
        `extra.#{@no_shop_key}`）。代表店を書いたら外す
      - "#{@origin_tag}" —— 代表店が発祥・元祖の店で、いまも営業しているとき
      - "#{@shop_why}:<語>" —— **店の 1 件だけ**。入れた理由（#{Enum.join(@shop_whys, " / ")}。上の「店の 1 件」）
      - "裏付け:<誰が名物として挙げているか>" —— 次の語から、確かめた頁があるものを全部:
        #{Enum.map_join(@backings, " / ", &elem(&1, 0))}
        （国 = 農林水産省「うちの郷土料理」など、県 = 県や県の観光協会、市区町村 = 市町村や地元の観光協会、
        商標 = 地域団体商標、大会 = ご当地グルメの大会への出展・受賞）。その頁の URL は `extra.sources` に
      - "提供店:<店の数>" —— #{Enum.join(@shop_counts, " / ")}（1 軒だけ・数軒・町に専門店が並ぶ／組合や公式の店舗一覧がある）
      - "#{@rank_tag}:<A〜E>" —— **百科事典に記事の無い 1 件だけ**（足した名産など）、どれくらい
        知られているか。A=全国から人が来る、B=その県を代表する、C=その市区町村で知られる、
        D=地元で親しまれている、E=それ以外。**迷ったら下の段に**してください（地図の丸の大きさに
        なります）。記事のある 1 件は記事の閲覧数で機械が決めるので付けません
      - "出典:OSM" / "出典:Overture" / "出典:#{@address_source_label}" / "出典:#{@ai_source_label}" / "#{@unplaced_tag}" / "#{Chiezo.locked_tag()}" は機械が付けます。
        **足したり消したりしないでください**
    - extra.shop: 代表店の手がかり（上の「代表店の決め方」）
    - extra.#{@shop_reason_key}: その店を代表店にした理由を 1 行（店の 1 件はその店を入れた理由）。
      確かめた頁に書いてある事実だけで、口コミの評点や感想は書かない（上の「代表店の決め方」）
    - extra.available_months: **提供の月**（その料理が食べられる・買える月）。`11-3`（11 月〜3 月）・
      `6,7,8`・`12-2,7` の形。**通年なら書かない**。確かめた頁に書いてあるときだけ
    - extra.season_note: 時期の補足を短く（「冬季のみ」「毎年 2 月の祭りの間だけ」）
    - extra.opening_hours: 代表店の営業時間を OpenStreetMap の `opening_hours` の書き方で
      （例 `Mo-Fr 11:00-14:30,17:30-22:00; Sa,Su,PH 11:00-21:00; We off`）。確かめたときだけ
      （辞典に営業時間がある店では辞典の値が使われます）
    - extra.municipality: 料理の市区町村（県全体の料理なら書かない）
    - extra.sources: 確かめた頁の URL の並び（5 つまで）
    - extra.checked_on: 代表店がいまもその料理を出していると確かめた日（`YYYY-MM-DD`。今日の日付）。
      代表店なしにしたときは、探して見つからなかった日
    - extra.#{@no_shop_key}: 代表店なしの理由を 1 行（"#{@no_shop_tag}" を付けたときだけ。代表店を書いたら null）
    - extra.#{@display_key}: 地図に出す名前。**見出しに土地の名が無い一般名の名物**は
      「徳島のスダチ」「沖縄のゴーヤー」のように土地を頭に付けて書き、**発祥の店・名物の店の
      店の 1 件**はそのグルメの名前を書く（上の「店の 1 件」。見出しのままでよければ書かない）。
      **見出しそのものは変えないでください**（同じ 1 件を指す鍵で、付け替えると弾かれます）
    - **ほかの extra の鍵は書かないでください**（1 件に持てる鍵の数に上限があります）。
      **Google マップや食べログなどの中身（口コミの本文・評点・写真・メニュー表）は写さないでください**
      —— 確かめるのに読むのはよいですが、残すのはそこから分かった事実と、確かめた頁の URL までです

    **消す 1 件**: tags に "#{Chiezo.tombstone_tag()}" を入れ、**body に消す理由を 1 行**
    （「どこにでもある料理でご当地と言えない」「2019 年に販売終了」のように、何をどう判断したか）。
    理由の無い墓標は、あとから誰にも直せません。
    """
  end

  @doc """
  travel-log からの依頼の前置き（`Chidori.Datasets.Requests` が補足の頭に付ける）。
  食事処の前置きは「店」の話なので、料理と代表店の言い方で書き直したもの。

  **報告は現地を見た人のもの**なので、食事処と同じく報告を先に済ませ、そのあと
  いつもの仕事も続けてもらいます。
  """
  def request_preface do
    """
    この補足は、**地図を使っている人が現地で見て書いた報告**です。
    **この県では、ほかの仕事より先に、この報告に答えてください。**
    **答えたら、そのあと上の依頼文のいつもの仕事も続けてください**（報告に答えただけで終えない）。

    - 名前は地図に出している料理か店の名前です。見出しの後ろの「（県名）」や「 (補足)」が
      落ちていることがあります —— **座標の近い、同じ名前の 1 件**を指しています
    - 「代表店が閉店」「もう出していない」「売っていない」と書かれたものは、**料理は消さずに、
      代表店を選び直してください**（決まりは上の依頼文のとおり。現地の報告を信じ、web で
      営業を確かめられない限り、その店は外す）。**店の 1 件**（tags に "#{@shop_tag}"）の
      「閉店」は、営業していると確かめられない限り墓標で消してください（body に「現地から閉店の報告」）
    - 「料理そのものが終わった」と書かれたもの（どの店でも出していない）は、営業していると
      確かめられない限り、墓標で消してください（body に「現地から終了の報告」）
    - 「ある」「追加」と書かれた料理は、上に無ければ足してください（座標の近くの店を代表店の
      手がかりにする。web で確かめられなくても、現地で見た報告なので足してよい。そのときは
      body に「現地からの報告（web では確かめられず）」と書き、**ほかは報告に書いてあったことだけに
      する** —— 確かめていない紹介文（由来・味・名物の様子）や時期・営業時間・裏付けを作らない。
      地図では確かめた紹介と同じ顔で並ぶので、作った文が本当のことに見えます）。上の「消したもの」に並んで
      いたら、新しく足さずに戻してください（tags に "#{Chiezo.restore_tag()}" を入れ、同じ見出しで返す）
    - 位置のずれの報告は、代表店の住所を確かめて `extra.shop` を書き直してください
      （座標は書かない。辞典から引き直されます）
    """
    |> String.trim_trailing()
  end

  @doc """
  travel-log からの依頼 1 件を、**どの県の区画で頼むか**（区画の鍵。決まらなければ nil）。

  名前の出てくる依頼（`[修正] 料理名 (緯度,経度)`）は、その座標の近くにある同じ名前の
  料理（消えたものも含む）の県へ —— 代表店は料理の県の外にあってよいので、座標の
  県とは限らない。見つからなければ・名前の無い依頼（`[追加]`）は、**座標のある県**へ
  （地図辞典の点の所属で読む。`Chidori.Chiezo.area_at/3`）。
  """
  def request_partition(%{text: text, lat: lat, lon: lon}) do
    with {:ok, base} <- Chidori.Datasets.base_url() do
      by_name(base, text, lat, lon) || by_point(base, lat, lon)
    else
      _unavailable -> nil
    end
  end

  # 料理を探す広さ（メートル）。地図に出ているのは代表店の座標そのものなので狭くてよい
  @request_meters 300

  defp by_name(base, text, lat, lon) do
    said = Chidori.Datasets.Requests.same_name(request_name(text))

    with true <- String.length(said) >= 2,
         {:ok, docs} <- Chiezo.nearby(base, @collection, lat, lon, @request_meters),
         %{} = doc <-
           Enum.find(docs, &(Chidori.Datasets.Requests.same_name(&1["title"] || "") == said)) do
      doc
      |> Map.get("tags", [])
      |> Enum.find_value(fn tag ->
        prefecture = prefecture_of_key(tag)
        prefecture && partition_key(prefecture)
      end)
    else
      _none -> nil
    end
  end

  defp by_point(base, lat, lon) do
    case Chiezo.area_at(base, lat, lon) do
      {:ok, prefecture} when prefecture in @prefectures -> partition_key(prefecture)
      _unknown -> nil
    end
  end

  # 依頼の 1 行目から料理の名前（`- [修正] 名前 (緯度,経度): 理由`）
  defp request_name(text) do
    text
    |> String.split("\n", parts: 2)
    |> List.first()
    |> String.replace(~r/^\s*-?\s*\[[^\]]*\]\s*/u, "")
    |> String.split("(", parts: 2)
    |> List.first()
    |> String.trim()
  end

  @doc """
  県ごとの進み具合（データ収集の画面に出す）。**数だけ**を返します（溜まったもの
  そのものは見せない決まり）。

  `{:ok, %{rows: [%{prefecture, key, dishes, shops, placed, pending, unresolved, no_shop}],
  unplaced_region: 件数, unresolved_total: 件数}}` か `{:error, 理由}`。

  - `dishes` —— 生きている 1 件の数（料理と店の両方。まだ AI が見ていないものを含む）
  - `shops` —— `dishes` のうち店の 1 件（`shop_tag/0`）。ほかの数は料理と店を分けない
  - `placed` —— 代表店あり。引き当たって座標を持つ料理（travel-log へ出せるもの。AI が見たあとなら）
  - `pending` —— 代表店まだ。座標が無く、代表店なしでもない料理（手がかりがまだ無いものと、
    引き当てできなかったもの。情報収集の回はこれが残る県に戻る）
  - `unresolved` —— `pending` のうち、手がかりを書いたが引き当てられなかった料理
    （Chiezo の `unresolved` の口）
  - `no_shop` —— 代表店なし。情報収集の AI が探したが、確実に食べられる・買える店が
    見つからなかった料理（`no_shop_tag/0`。座標が無いので書き出さない）

  `dishes = placed + pending + no_shop`。**「AI が見たか」（未確認）は数えません** ——
  名簿の料理は情報収集が目を通すと印が外れるので、代表店がまだでも 0 になり、
  「この県は片付いた」と読めてしまう。

  **数えるために消えたものも受け取って、こちらで落とします**（Chiezo の読み口は既定で
  未レビューも外すので、それでは名簿の数が出ない）。選り分け直しではなく、数えるだけ。

  引き当てられなかったものの口を持たない Chiezo では、その数だけ数えません
  （`unresolved_total: nil`。ほかの数は出す）。
  """
  def progress do
    with {:ok, base} <- Chidori.Datasets.base_url(),
         {:ok, docs} <- all_docs(base) do
      unresolved =
        case Chiezo.unresolved(base, @collection) do
          {:ok, found} -> found
          {:error, _reason} -> %{total: nil, rows: []}
        end

      alive = Enum.reject(docs, &(Chiezo.removed_tag() in (&1["tags"] || [])))
      waiting = alive |> Enum.filter(&(shop_state(&1) == :pending)) |> Map.new(&{&1["title"], &1})

      # 引き当てできずは代表店まだのうち（座標を人が固定した料理・代表店なしは数えない）
      failed =
        unresolved.rows
        |> Enum.flat_map(fn row ->
          case waiting[row["title"]] do
            nil -> []
            doc -> [region_of(doc)]
          end
        end)
        |> Enum.frequencies()

      by_region = Enum.group_by(alive, &region_of/1)
      # 引き当てできなかった理由（Chiezo が控えたもの。見出し → 理由）
      reasons = Map.new(unresolved.rows, &{&1["title"], &1["reason"]})

      rows =
        for prefecture <- prefecture_order() do
          states = by_region |> Map.get(prefecture, []) |> Enum.frequencies_by(&shop_state/1)

          %{
            prefecture: prefecture,
            key: partition_key(prefecture),
            dishes: states |> Map.values() |> Enum.sum(),
            shops: by_region |> Map.get(prefecture, []) |> Enum.count(&shop?/1),
            placed: Map.get(states, :placed, 0),
            pending: Map.get(states, :pending, 0),
            unresolved: Map.get(failed, prefecture, 0),
            no_shop: Map.get(states, :no_shop, 0),
            # **県を選んだときに並べる、代表店まだ・代表店なしの料理**（理由つき）
            pending_items: items(by_region, prefecture, :pending, reasons),
            no_shop_items: items(by_region, prefecture, :no_shop, reasons)
          }
        end

      {:ok,
       %{
         rows: rows,
         unplaced_region: length(Map.get(by_region, nil, [])),
         unresolved_total: unresolved.total
       }}
    end
  end

  # 県の代表店まだ・代表店なしの料理（見出しの順）と、そうなっている理由。
  # 代表店まだは引き当てできなかった理由（Chiezo の控え）か、手がかりがまだ無いこと、
  # 代表店なしは AI が書いた理由（`extra.no_shop`）
  defp items(by_region, prefecture, state, reasons) do
    by_region
    |> Map.get(prefecture, [])
    |> Enum.filter(&(shop_state(&1) == state))
    |> Enum.map(fn doc ->
      %{title: doc["title"], reason: item_reason(state, doc, reasons)}
    end)
    |> Enum.sort_by(& &1.title)
  end

  defp item_reason(:pending, doc, reasons),
    do: reasons[doc["title"]] || "代表店の手がかりがまだ無い（情報収集の回で探す）"

  defp item_reason(:no_shop, doc, _reasons) do
    case get_in(doc, ["extra", @no_shop_key]) do
      reason when is_binary(reason) and reason != "" -> reason
      _other -> "理由が書かれていない"
    end
  end

  @doc """
  1 件の代表店の状態。`:placed`（座標がある）・`:no_shop`（代表店なしの印）・
  `:pending`（それ以外 = 代表店まだ）。**座標が先**（人が位置を固定した料理は地図に置ける）。
  """
  def shop_state(doc) do
    cond do
      placed?(doc) -> :placed
      @no_shop_tag in (doc["tags"] || []) -> :no_shop
      true -> :pending
    end
  end

  # 1 回に引く件数（Chiezo 側の上限）
  @page_limit 500

  defp all_docs(base, offset \\ 0, acc \\ []) do
    case Chiezo.spot_docs(base, @collection, kind_tag(), offset, @page_limit,
           include_removed: true
         ) do
      {:ok, %{docs: []}} ->
        {:ok, acc}

      {:ok, %{total: total, docs: docs}} ->
        got = acc ++ docs
        if length(got) >= total, do: {:ok, got}, else: all_docs(base, length(got), got)

      {:error, reason} ->
        {:error, reason}
    end
  end

  @doc "1 件の県（語彙に無い値・無ければ nil）。"
  def region_of(doc) do
    doc
    |> Map.get("tags", [])
    |> Enum.find_value(fn tag -> is_binary(tag) && prefecture_of_key(tag) end)
  end

  defp placed?(doc) do
    extra = doc["extra"] || %{}
    is_number(extra["lat"]) and is_number(extra["lon"])
  end

  # ── 空いている欄を埋める 1 回（`Chidori.Datasets.Blanks`。食事処と同じ形） ──

  # 空いていたら埋めてもらう欄。**代表店のある 1 件だけ**を数える（代表店が無ければ、
  # 営業時間も理由も書きようがない）。営業時間が無いと travel-log の「今営業中」に
  # かからないので先頭に置く
  @blank_fields [opening_hours: "代表店の営業時間", shop_reason: "代表店の理由"]
  @fill_default 20
  # 上限は Chiezo の割り込みが名指しを受け取る数（`MAX_FOCUS_TITLES`）
  @fill_max 50

  @doc "空いていたら埋めてもらう欄（鍵 → 画面の名前。並びが画面の並び）。"
  def blank_fields, do: @blank_fields

  @doc "空欄を埋める 1 回に名指しする数の既定と上限（`{既定, 上限}`）。"
  def fill_counts, do: {@fill_default, @fill_max}

  @doc "画面で数えるときの単位。"
  def blank_unit, do: "件"

  @doc "1 件の空いている欄（`blank_fields/0` の鍵の並び）。代表店の無い 1 件は空にしない。"
  def blanks(doc) do
    extra = doc["extra"] || %{}

    if placed?(doc) do
      for {field, _label} <- @blank_fields, text(extra[Atom.to_string(field)]) == "", do: field
    else
      []
    end
  end

  @doc """
  代表店のある 1 件のうち、空いている欄のあるもの。`{:ok, %{total: 代表店のある数, shops: [...]}}`。
  **読むのは AI が目を通した 1 件だけ**（Chiezo の読み口が、まだのものと消えたものを外す）。
  """
  def blank_report(_dataset) do
    with {:ok, base} <- Chidori.Datasets.base_url(),
         {:ok, docs} <- reviewed_docs(base) do
      placed = Enum.filter(docs, &placed?/1)

      shops =
        for doc <- placed,
            (missing = blanks(doc)) != [],
            do: %{title: doc["title"], missing: missing}

      {:ok, %{total: length(placed), shops: shops}}
    end
  end

  defp reviewed_docs(base, offset \\ 0, acc \\ []) do
    case Chiezo.spot_docs(base, @collection, kind_tag(), offset, @page_limit) do
      {:ok, %{docs: []}} ->
        {:ok, acc}

      {:ok, %{total: total, docs: docs}} ->
        got = acc ++ docs
        if length(got) >= total, do: {:ok, got}, else: reviewed_docs(base, length(got), got)

      {:error, reason} ->
        {:error, reason}
    end
  end

  @doc "欄ごとの空いている数（`blank_fields/0` の並び。空いているものの無い欄は出さない）。"
  def blank_counts(items), do: Chidori.Datasets.Blanks.counts(items, @blank_fields)

  @doc """
  空欄を埋める 1 回の頼みごと（`Chidori.Datasets.fill_blanks/3` に渡すもの）。
  **県に縛らず、全国から名指しします**（Chiezo の割り込みの `titles`。県を渡すと情報収集の印が
  付き、その県の見直しが一周先へ回る）。営業時間の無いものを先に、空いている欄の多いものから
  `count` 件（同じ並びの中は毎回混ぜる。`Chidori.Datasets.Blanks.pick/5`）。当てはまるものが無ければ `:nothing`。
  """
  def fill_request(items, fields, count) do
    wanted = for {field, _label} <- @blank_fields, field in fields, do: field
    picked = Chidori.Datasets.Blanks.pick(items, wanted, count, @fill_max, :opening_hours)

    case picked do
      [] ->
        :nothing

      _some ->
        {:ok,
         %{
           titles: Enum.map(picked, & &1.title),
           note: "挙げた #{length(picked)} 件の代表店について、空いている欄（#{blank_labels(wanted)}）だけを調べて埋めてください。",
           prompt: fill_prompt(picked)
         }}
    end
  end

  defp blank_labels(fields), do: Enum.map_join(fields, "・", &@blank_fields[&1])

  @doc """
  空欄を埋める 1 回の依頼文（`fill_request/3`）。**保存しない**（その回だけ Chiezo に渡す）。
  代表店は変えさせない（選び直すのは情報収集の仕事で、ここは空欄を埋めるだけ）。
  """
  def fill_prompt(items) do
    list =
      Enum.map_join(items, "\n", fn item -> "- #{item.title}: #{blank_labels(item.missing)}" end)

    """
    「ご当地グルメ」の一覧のうち、**下に挙げた 1 件の空いている欄だけ**を埋めてください。
    travel-log という地図アプリのスポットとして使います。どれも代表店（`extra.shop`）が決まっています。

    **埋めてほしい 1 件と、空いている欄**
    #{list}

    {current}

    **1 件ずつ、代表店の公式の頁・県や観光協会の紹介・地図サービスの店の情報を開いて調べてください。**
    **確かめられたものだけ**書き、分からない欄は空けたままにしてください（当てずっぽうで埋めると、
    正しい情報に見えてしまいます）。この回に時間の制限はありません。

    - 代表店の営業時間（`extra.opening_hours`）…… 代表店の営業日と営業時間を OpenStreetMap の
      `opening_hours` の書き方で（例 `Mo-Fr 11:00-14:30,17:30-22:00; Sa,Su,PH 11:00-21:00; We off`）。
      **travel-log の「今営業中」の絞り込みはここから読む**ので、いちばん大事です。
      年末年始などの休み（`Dec 31-Jan 03 off`）、季節ごとの営業時間（`Apr-Oct 09:00-17:00; Nov-Mar 09:00-16:00`）、
      第何曜日の定休日（`We[2,4] off`）もこの書き方で書けます
    - 代表店の理由（`extra.#{@shop_reason_key}`）…… その店を代表店にした理由を 1 行。**確かめた頁に書いてある
      事実だけ**（創業の年・発祥や本店であること・公的な紹介・駅からの近さ）で、口コミの評点や感想は書かない

    **代表店（`extra.shop`）は変えないでください**（選び直すのは別の回の仕事です）。調べている途中で
    代表店が閉店していると分かったら、その 1 件は返さずに、`checked` にそう書いてください。**返すときは、いま付いているタグと本文をそのまま残してください**
    （返した内容で置き換わります）。書いてよい脇書きは上の 2 つと `extra.sources`（確かめた頁の URL の
    並び。5 つまで）だけです。

    **埋めた 1 件だけを返してください。** 1 つも埋まらなかった 1 件は返さなくて構いません。

    **何を調べたかを、答えの `checked` に 1 行ずつ書いてください**（items と並べて
    `"checked": ["…", "…"]`）。埋まらなかった欄も、どこを見て見つからなかったかを残してください。
    """
  end

  # ── travel-log への書き出し（`Chidori.Datasets.TravelLog` が呼ぶ） ──

  @csv_header ~w(name lat lng region rank series categories description available_months opening_hours key)

  @doc "spots.csv の列（提供の時期と営業時間の 2 列を足したもの）。"
  def csv_header, do: @csv_header

  @doc "travel-log のカテゴリの並び（絞り込みの並び）。"
  def category_order do
    [@shop_category, @origin_tag] ++
      Enum.map(@shop_rules, &elem(&1, 0)) ++
      [@season_category] ++
      Enum.map(@backings, &elem(&1, 1)) ++ [@doubt_tag, @checked_category]
  end

  @doc """
  1 件をスポットの行にします。**地図に置けないものは作りません**（nil）——
  代表店が引き当たっていない（座標が無い）・県が語彙に無いもの。
  """
  def spot(doc, dataset) do
    tags = Map.get(doc, "tags") || []
    extra = Map.get(doc, "extra") || %{}
    region = region_of(doc)
    lat = number(extra["lat"])
    lon = number(extra["lon"])

    # 地図に出す名前は AI が書いたものを先に（見出しは鍵なので変えられない）
    name =
      case text(extra[@display_key]) do
        "" -> dish_name(doc["title"], region)
        shown -> shown
      end

    if name == "" or is_nil(lat) or is_nil(lon) or is_nil(region) do
      nil
    else
      %{
        "name" => name,
        "lat" => lat,
        "lng" => lon,
        "region" => region,
        "rank" => rank(tags, extra),
        "series" => series_of(tags),
        "categories" => tags |> categories(extra) |> Enum.join("|"),
        "description" => description(tags, extra),
        "available_months" => text(extra["available_months"]),
        "opening_hours" => text(extra["opening_hours"]),
        "key" => Chidori.Datasets.TravelLog.spot_key(doc["doc_id"], dataset)
      }
    end
  end

  @doc """
  **料理の代表店と店の 1 件が同じ店を指すとき、片方だけを書き出します**（`{1 件, 行}` の
  並びを受け取り、落とすほうの行を nil にして返す。`Chidori.Datasets.TravelLog` は nil の
  1 件の key を exclude.txt に入れるので、前に読み込んでいれば消える）。

  有名店を店名で入れたので、系統の料理と発祥の店（家系ラーメンと吉村家）が両方あると
  同じ店にピンが 2 本立つ。情報収集の依頼文でも片付けさせているが（`shop_item_rule`）、
  回ってくるまでの間も地図には二重のピンが出るので、書き出す段で機械でも落とす。

  - **同じ店とみなすのは、辞典の同じ記録に引き当たっているときだけ**（Chiezo が
    `extra.shop.identity` に運ぶ元の記録の鍵。鍵の無い引き当ては `extra.shop.ref` =
    「辞典:見出し」で比べる）。名前では突き合わせない —— 同じ名前の別の店舗がある
  - **残すのはいつも料理**（依頼文と同じ向き。利用者の決めごと）。スポットの名前は料理名で、
    店名は説明の代表店の行で出る。`提供店:1`（その店でしか食べられない）でも料理を残す
    —— 訪ねる人が探すのは「その土地で何を食べるか」で、店名だけのピンでは何の店か読めない
  - 店を落としたぶん、同じ店にいる料理はいくつあっても全部残す
  """
  def without_same_shop(made) do
    indexed = Enum.with_index(made)

    placed =
      for {{doc, row}, index} <- indexed,
          row != nil,
          keys = shop_keys(doc),
          MapSet.size(keys) > 0,
          do: {index, doc, keys}

    {shops, dishes} = Enum.split_with(placed, fn {_index, doc, _keys} -> shop?(doc) end)

    drop =
      MapSet.new(
        for {index, _doc, keys} <- shops,
            Enum.any?(dishes, fn {_, _, dish_keys} -> not MapSet.disjoint?(keys, dish_keys) end),
            do: index
      )

    for {{doc, row}, index} <- indexed do
      if MapSet.member?(drop, index), do: {doc, nil}, else: {doc, row}
    end
  end

  # 代表店が引き当たった辞典の記録の鍵（元の記録の鍵。無ければ「辞典:見出し」）
  defp shop_keys(doc) do
    shop = (Map.get(doc, "extra") || %{})["shop"]

    keys =
      cond do
        not is_map(shop) or not is_binary(shop["resolved_at"]) or shop["unresolved"] ->
          []

        is_list(shop["identity"]) and Enum.any?(shop["identity"], &(is_binary(&1) and &1 != "")) ->
          Enum.filter(shop["identity"], &(is_binary(&1) and &1 != ""))

        is_binary(shop["ref"]) and shop["ref"] != "" ->
          ["ref:" <> shop["ref"]]

        true ->
          []
      end

    MapSet.new(keys)
  end

  @doc """
  ランク（A〜E）。**段階は機械で**決めます。材料は 3 つで、**いちばん高い段**を採ります。

  1. 裏付け（誰が名物として挙げているか）と提供している店の数

     | ランク | 決まり |
     |---|---|
     | A | 国か地域団体商標の裏付けがあり、提供店が多数 |
     | B | 国・商標・県のどれかの裏付けがある |
     | C | 市区町村の裏付けがある |
     | D | 公的な裏付けは無いが、提供店が数軒以上ある |
     | E | それ以外 |

  2. 百科事典の月の閲覧数（`extra.pageviews_month`。名簿が記事から運ぶ）——
     2000 以上で A・500 以上で B・100 以上で C・記事があれば D。
     **食材は C まで**（記事が果物や魚としても引かれ、名物としての知名度より伸びる）
  3. 記事の無い 1 件（AI が足した名産など）だけ、AI の見立て（タグ「ランク:」）。
     **B まで**（A は機械の材料で決まるものだけにして、丸の大きさの天井を保つ）

  A が多すぎると丸の大きさが何も表さなくなるので、A は「国か商標」と「多数」の両方か、
  閲覧数の上位だけ。
  """
  def rank(tags, extra \\ %{}) do
    Enum.min([backing_rank(tags), fame_rank(tags, extra), ai_rank(tags, extra)])
  end

  defp backing_rank(tags) do
    backed = MapSet.new(tagged(tags, "裏付け"))
    shops = tags |> tagged("提供店") |> List.first()
    national = MapSet.member?(backed, "国") or MapSet.member?(backed, "商標")

    cond do
      national and shops == "多数" -> "A"
      national or MapSet.member?(backed, "県") -> "B"
      MapSet.member?(backed, "市区町村") -> "C"
      shops in ["数軒", "多数"] -> "D"
      true -> "E"
    end
  end

  defp fame_rank(tags, extra) do
    case pageviews(extra) do
      nil ->
        "E"

      views ->
        rank =
          Enum.find_value(@fame_steps, "D", fn {floor, rank} -> if views >= floor, do: rank end)

        if Enum.any?(@produce_kinds, &("#{genre_tag()}:#{&1}" in tags)),
          do: Enum.max([rank, "C"]),
          else: rank
    end
  end

  # AI の見立ては記事の無い 1 件だけ（記事があれば閲覧数のほうが確か）
  defp ai_rank(tags, extra) do
    with nil <- pageviews(extra),
         rank when rank in ~w(A B C D E) <- tags |> tagged(@rank_tag) |> List.first() do
      Enum.max([rank, @ai_rank_ceiling])
    else
      _ -> "E"
    end
  end

  defp pageviews(extra) do
    case Map.get(extra || %{}, "pageviews_month") do
      n when is_integer(n) and n >= 0 -> n
      n when is_float(n) and n >= 0 -> trunc(n)
      _ -> nil
    end
  end

  @doc "1 件の種類（travel-log のシリーズ）。語彙から外してまとめた種類は、まとめた先で読む。"
  def series_of(tags) do
    case tags |> tagged(genre_tag()) |> List.first() do
      nil -> ""
      kind -> Map.get(@merged_kinds, kind, kind)
    end
  end

  @doc "1 件のカテゴリ（`category_order/0` の並び。語彙に無い語は落とす）。"
  def categories(tags, extra) do
    have =
      MapSet.new(
        [if(@shop_tag in tags, do: @shop_category), if(@origin_tag in tags, do: @origin_tag)] ++
          Enum.map(tagged(tags, "代表店"), & &1) ++
          [if(text(extra["available_months"]) != "", do: @season_category)] ++
          for(
            value <- tagged(tags, "裏付け"),
            {^value, label} <- @backings,
            do: label
          ) ++
          [
            if(@doubt_tag in tags, do: @doubt_tag),
            if(Chiezo.locked_tag() in tags, do: @checked_category)
          ]
      )

    Enum.filter(category_order(), &MapSet.member?(have, &1))
  end

  @doc """
  説明文。**選定理由・代表店の名前と選んだ決まり・代表店の理由・提供の時期・営業時間・出典**を
  1 行ずつ（店の 1 件は代表店ではなく「店:」で、その店自身・本店を書く）。
  料理そのものの説明（本文）は入れません —— 名簿の 1 件は百科事典の冒頭を持っていて、
  写すと CC BY-SA の帰属と継承が付く。座標の出どころ（辞典ごとにライセンスが違う）も添える。

  - **選定理由**（なぜご当地グルメなのか）は、タグ「裏付け:」から機械で組む（AI に文を書かせない。
    裏付けの無い 1 件には出さない）
  - **代表店の理由**（なぜこの店か）は、AI が `extra.shop_reason` に書いた 1 行（確かめた頁に
    基づく事実だけ）。店の 1 件では「選んだ理由」と書く
  """
  def description(tags, extra) do
    [
      backing_line(tags),
      shop_line(tags, extra),
      shop_reason_line(tags, extra),
      season_line(extra),
      hours_line(extra),
      sources_line(extra),
      coords_line(tags, extra)
    ]
    |> Enum.reject(&(&1 == ""))
    |> Enum.join("\n")
  end

  defp shop_line(tags, extra) do
    shop = if is_map(extra["shop"]), do: extra["shop"], else: %{}

    case text(shop["name"]) do
      "" ->
        ""

      shop_name ->
        reasons =
          for(value <- tagged(tags, "代表店"), {^value, label} <- @shop_rules, do: label) ++
            if(@origin_tag in tags, do: ["発祥の店"], else: [])

        why = if reasons == [], do: "", else: "（#{Enum.join(reasons, "・")}）"
        where = text(shop["address"])

        head = if @shop_tag in tags, do: "店", else: "代表店"
        "#{head}: #{shop_name}#{why}" <> if(where == "", do: "", else: "／#{where}")
    end
  end

  # 選定理由（「選定理由: 国（農林水産省など）・県や県の観光協会が名物として紹介、地域団体商標に登録」）
  defp backing_line(tags) do
    backed = tagged(tags, "裏付け")

    {by, says} =
      @backings
      |> Enum.map(fn {value, _label} -> value end)
      |> Enum.filter(&(&1 in backed))
      |> Enum.map(&Map.fetch!(@backing_reasons, &1))
      |> Enum.split_with(&match?({:by, _}, &1))

    parts =
      if(by == [], do: [], else: [Enum.map_join(by, "・", &elem(&1, 1)) <> "が名物として紹介"]) ++
        Enum.map(says, &elem(&1, 1))

    if parts == [], do: "", else: "選定理由: " <> Enum.join(parts, "、")
  end

  # 代表店の理由（AI が書いた 1 行。代表店の名前が無ければ出さない —— 店の無い理由は読めない）
  defp shop_reason_line(tags, extra) do
    shop = if is_map(extra["shop"]), do: extra["shop"], else: %{}

    case {text(shop["name"]), text(extra[@shop_reason_key])} do
      {"", _reason} -> ""
      {_name, ""} -> ""
      {_name, reason} -> if(@shop_tag in tags, do: "選んだ理由: ", else: "代表店の理由: ") <> reason
    end
  end

  defp season_line(extra) do
    months = text(extra["available_months"])
    note = text(extra["season_note"])

    case {months_text(months), note} do
      {"", ""} -> ""
      {"", note} -> "提供の時期: #{note}"
      {months, ""} -> "提供の時期: #{months}"
      {months, note} -> "提供の時期: #{months}（#{note}）"
    end
  end

  @doc "月の並び（`11-3,7`）を日本語に（`11〜3月・7月`）。読めなければ空。"
  def months_text(months) when is_binary(months) and months != "" do
    parts = String.split(months, ",", trim: true)

    if Enum.all?(parts, &(&1 =~ ~r/^\d{1,2}(-\d{1,2})?$/)) do
      Enum.map_join(parts, "・", fn part ->
        case String.split(part, "-") do
          [from, to] -> "#{from}〜#{to}月"
          [one] -> "#{one}月"
        end
      end)
    else
      ""
    end
  end

  def months_text(_months), do: ""

  defp hours_line(extra) do
    case text(extra["opening_hours"]) do
      "" -> ""
      hours -> "営業時間: " <> (Chidori.Datasets.OpeningHours.to_japanese(hours) || hours)
    end
  end

  # 出典（`extra.url` と `extra.sources`。http/https だけ、重複を落として 3 つまで）。
  # 百科事典の記事は travel-log の決まりの `[ja.wikipedia:記事名]` で書く
  # （向こうがアイコン付きのリンクに描く。URL のままだと長いうえ、日本語が % で崩れる）
  @shown_sources 3
  defp sources_line(extra) do
    urls =
      [extra["url"] | List.wrap(extra["sources"])]
      |> Enum.map(&Chidori.SafeUrl.href/1)
      |> Enum.reject(&is_nil/1)
      |> Enum.uniq()
      |> Enum.take(@shown_sources)

    if urls == [], do: "", else: "出典: " <> Enum.map_join(urls, " ", &source_ref/1)
  end

  defp source_ref(url) do
    case URI.parse(url) do
      %URI{host: "ja.wikipedia.org", path: "/wiki/" <> article} ->
        "[ja.wikipedia:#{URI.decode(article)}]"

      _other ->
        url
    end
  end

  defp coords_line(tags, extra) do
    from = tagged(tags, "出典")

    cond do
      # **住所から引いた座標は、そう書く**（店の辞典で確かめた位置ではなく、街区の代表点）。
      # 位置参照情報は加工して使うとき出典と整備年を書く約束（利用約款 第 2 条 3）
      @address_source_label in from ->
        "座標: 代表店の住所の街区（街区レベル位置参照情報 国土交通省#{isj_year(extra)}を加工）"

      # **AI が地図で確かめた座標も、そう書く**（辞典にも住所にも当たらなかった店。Chiezo の `ai_fallback`）
      @ai_source_label in from ->
        "座標: 代表店の位置（地図サービスで確かめた位置）"

      from == [] ->
        ""

      true ->
        names =
          Enum.map(from, fn
            "OSM" -> "OpenStreetMap"
            "Overture" -> "Overture Maps"
            other -> other
          end)

        "座標: 代表店の位置（#{Enum.join(names, " / ")}）"
    end
  end

  @doc """
  位置参照情報の版（`24.0a`）から整備年（「 令和7年度」。読めなければ空）。版の頭の数は
  平成 30 年度が 17 で、年に 1 つずつ上がる。`clue` は引き当てた場所を持つ脇書きの鍵
  （ご当地グルメは `shop`）。位置参照情報は加工して使うとき出典と整備年を書く約束
  （利用約款 第 2 条 3）なので、アニメ聖地の書き出しも使う
  """
  def isj_year(extra, clue \\ "shop") do
    shop = if is_map(extra[clue]), do: extra[clue], else: %{}

    case Integer.parse(text(shop["version"])) do
      {major, _rest} when major > 17 -> " 令和#{major - 17}年度"
      _ -> ""
    end
  end

  @doc """
  地図に出す料理・店の名前。県ごとに分けた 1 件の「（県名）」と、百科事典の見分けの補足
  （「チェルシー (菓子)」の「 (菓子)」・「梅園 (和菓子店)」の「 (和菓子店)」）を落とします（地図に出るのは名前なので、
  機械の都合は見せない。travel-log 側の鍵は doc_id）。
  """
  def dish_name(title, region) do
    title
    |> text()
    |> then(fn name ->
      if region, do: String.replace_suffix(name, "（#{region}）", ""), else: name
    end)
    |> String.replace(~r/\s+\([^()]*\)$/u, "")
    |> String.trim()
  end

  # そのタグの値だけを、付いている順で
  defp tagged(tags, prefix) do
    tags
    |> Enum.filter(&(is_binary(&1) and String.starts_with?(&1, prefix <> ":")))
    |> Enum.map(&String.trim(String.replace_prefix(&1, prefix <> ":", "")))
    |> Enum.reject(&(&1 == ""))
  end

  defp number(value) when is_number(value), do: value
  defp number(_value), do: nil

  # 見出しや本文に混じる制御文字を落とす（`Chidori.Datasets.TravelLog` と同じ）
  defp text(value) when is_binary(value) do
    value |> String.replace(~r/[\x00-\x08\x0b\x0c\x0e-\x1f]/, "") |> String.trim()
  end

  defp text(_value), do: ""
end
