    - 3〜5 が残っている回は、この 6 はしないでください

    **4〜6 は全部でなくて構いません。** 見直せなかった料理は申告しないでください
    （`not_reviewed` に入れない）。

    #{ending_rule()}

    #{scope_rule()}

    #{shop_item_rule()}

    #{item_format()}

    **直した料理・消す料理・足す料理だけを返してください。** 直すところが無かった料理は
    返さなくて構いません（そのまま残ります）。

    **何を調べたかを、答えの `checked` に 1 行ずつ書いてください**（items と並べて
    `"checked": ["…", "…"]`）。例: "ソースカツ丼: 本店の公式メニューで提供を確認、代表店を本店に"、
    "見直し: 5 品の代表店の頁を確認、変更なし"。地図には載りません。
    """
  end

  @doc """
  ざっと見るの依頼文。**整理の ②〜④ だけ**（名簿から入った料理の確認・代表店を決める・
  空欄を埋める）を、2 時間おきに 1 県ずつ回して一周で止まる（`sweeps/0`）。

  **空欄を埋める段（3）は飛ばさないよう強く頼む** —— 「全部でなくて構いません」と書いた
  頃は、軽い相手が名簿の確認と代表店だけで終え、空欄をほとんど埋めなかった（1 県で
  代表店の理由が空のもの 122 件が残ったまま）。

  整理は 1 回に料理 20 品までで 12 時間おきなので、名簿の 2000 件近くを片付けるのに
  1 か月以上かかる。手の付いていないものはこちらが早く片付け、見直し・名産を足す・
  travel-log からの報告は整理に残す（判断の重い回は、頼む相手を別に選べるように）。
  段の文は整理と同じもの（書き分けると、片方が直したものをもう片方が戻す）。
  """
  def scan_prompt do
    """
    #{prompt_head()}

    **この回は、まだ手の付いていないものを片付ける回です。** 確かめてから日の経った料理の
    見直しと、名簿に無い名産を足すのは別の回がします。

    #{roster_step(1)}

    #{shop_step(2, "別の回が、確かめてから日の経ったものを探し直します")}

