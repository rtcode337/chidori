    申告しないでください（`not_reviewed` に入れない）。

    #{ending_rule()}

    #{scope_rule()}

    #{shop_item_rule()}

    #{item_format()}

    **直した料理・消す料理・足す料理だけを返してください。** 直すところが無かった料理は
    返さなくて構いません（そのまま残ります）。

