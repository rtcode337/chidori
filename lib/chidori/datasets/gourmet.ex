        %{pattern: "^(.+?[都道府県])の#{@paired_kind}$", with: "{1}の#{@paired_with}"},
        %{pattern: "^(?:#{Enum.join(@national_kinds, "|")})$", with_pattern: culture_pattern()}
      ],
      tags:
        [
          %{const: kind_tag()},
          %{
            pattern: "^(.+?[都道府県])の(?:#{Enum.join(roster_kinds(), "|")})$",
            format: "#{area_tag()}:{1}",
            map: Map.new(@prefectures, &{&1, &1})
          },
          # **県の括りで県が決まらなかった記事（全国の括りで入ってきたもの）は、県の食文化から
          # 読む**。`"all"` は当たった県ごとに作る（2 県なら `split` で 2 件に分かれる）。
          # 県の括りで県が決まった記事には作らない —— 麺料理の県と別の県の食文化を持つ記事が
          # 県を 2 つ持つと、要らない 1 件が増える
          %{
            pattern: culture_pattern(),
            format: "#{area_tag()}:{1}",
            map: Map.new(@prefectures, &{&1, &1}),
            fallback: "all"
          },
          # **県の括りでも県の食文化でも県が決まらなかった記事は、市区町村の付いた括りから
          # 読む**（店の種類のカテゴリだけで入った店。市区町村から県は地図辞典で引く `area_of`。
          # 同じ名前の市が 2 県にあるときは作らない）
          %{
            pattern: @shop_city_pattern,
            format: "#{area_tag()}:{1}",
            fallback: true,
            area_of: %{
              source: "osm_japan",
              feature: ["place=city", "place=town", "place=village"]
            }
          },
          # **それでも県が決まらなかった店は「不明」の区画へ**（`unknown_region/0`）。名簿から
          # 落とさず、手入れの回に AI が本店の県へ付け替える（記事が全国の括りしか持たない名店
          # —— 蒙古タンメン中本のような —— が入らなかった）
          %{
            pattern: "^(?:#{Enum.join(shop_entry_categories(), "|")})$",
            format: "#{area_tag()}:#{@unknown_region}",
            fallback: true
          },
          # **店の記事は店の 1 件**（店の種類のカテゴリか、県の飲食店に入っている記事）
          %{
            pattern: "^(?:#{Enum.join(@shop_categories, "|")}|.+?[都道府県]の#{@shop_kind})$",
            format: @shop_tag
          }
        ] ++ kind_rules(),
      # **知名度（月の閲覧数）だけ運ぶ**。ランクの材料（`rank/2`）。1 件の脇書きは鍵の数に
      # 上限があるので、読まないものは載せない
      extra: ["pageviews_month"],
      split: %{prefix: "#{area_tag()}:", title: "{title}（{value}）"}
    }
  end

  # 県の食文化のカテゴリ（組の相手と、全国の括りの県を読むところ）
  defp culture_pattern, do: "^(.+?[都道府県])の#{@paired_with}$"

  # 種類の読み替え。**最初の 1 つだけ**（2 つ目からは前が作っていれば作らない）
  defp kind_rules do
    @kind_rules
    |> Enum.with_index()
    |> Enum.map(fn {written, index} ->
      rule = kind_rule(written)
      if index == 0, do: rule, else: Map.put(rule, :fallback, true)
    end)
  end

  defp kind_rule({pattern, kind}), do: %{pattern: pattern, format: "#{genre_tag()}:#{kind}"}

  # 表のぶん（カテゴリの名前そのものを捕まえて、表で種類に読み替える）
  defp kind_rule(table) when is_map(table) do
    names = table |> Map.keys() |> Enum.map_join("|", &Regex.escape/1)
    %{pattern: "^(#{names})$", format: "#{genre_tag()}:{1}", map: table}
  end

  @doc """
  区画の割り方（県 47 と「不明」。並べた順が 1 周目の順）。**県の分からない 1 件の区画**
  （`unknown_region/0`）を最後に置く —— 店の種類のカテゴリしか持たない店（記事から県も
  市区町村も読めない）を名簿から落とさず、手入れの回に正しい県へ付け替えさせるため。
  """
  def partition do
    %{
      by: "tag",
      prefix: "#{area_tag()}:",
      values: prefecture_order() ++ [@unknown_region],
      target: 5000
    }
  end

  @doc "県の分からない 1 件の区画の値（`地域:不明`）。"
  def unknown_region, do: @unknown_region

  @doc """
  代表店の引き当て（Chiezo の `resolve`）。AI は `extra.shop` に手がかりを書き、
  Chiezo が地図辞典（先）と店舗辞典を引いて座標を運ぶ。**営業時間は辞典の値が先**。
  """
  def resolve do
    %{
      clue: "shop",
      sources: [
        %{source: "osm_japan", identity: ["osm_type", "osm_id"], tag: "出典:OSM"},
        # **店舗辞典の座標は住所の街区で確かめる**（`check_coords`）。住所は合っているのに座標が
        # 数 km ずれた記録・住所そのものが違う記録が多い。地図辞典の点と重ならず、住所の街区から
        # 離れていれば、座標だけ街区の代表点に替える
        %{
          source: "overture_japan",
          identity: ["overture_id"],
          tag: "出典:Overture",
          check_coords: true
        }
      ],
      # **店の辞典に無い店は、AI が確かめた住所から座標を引く**（最後の段。街区まで当たった
      # ときだけ）。辞典の漏れを AI に探させているのに、見つけた店ほど地図に置けなかった
      address: %{source: "address_jp", tag: "出典:#{@address_source_label}"},
      area_tag: "#{area_tag()}:",
      agree_meters: 100,
      carry: ["address", "phone", "website", "opening_hours"],
      to_extra: %{opening_hours: "opening_hours"},
      failed_tag: @unplaced_tag,
      # **手がかりがまだ無い料理にも代表店未定を付ける**（情報収集の県の足止めと、画面の
      # 「代表店まだ」に数える）。代表店なしの印の付いた料理には付けない
      failed_when_missing: true,
      none_tag: @no_shop_tag,
      ai_coords: false,
      # **辞典にも住所にも当たらないときだけ、AI が地図で確かめた座標で置く**（最後の段）。
      # 辞典の点も間違ううえ、辞典に無い小さな店は辞典では置けない。印で見分ける
      ai_fallback: %{tag: "出典:#{@ai_source_label}"}
    }
  end

  @doc "脇書きの書式（travel-log の CSV の 2 列。崩れた値は Chiezo が焼く前に落とす）。"
  def formats, do: %{available_months: "months", opening_hours: "opening_hours"}

  @doc """
  巡回 3 本（機械収集 → ざっと見る → 情報収集）。**1 回に 1 県**（1 県ぶんの調べものは重く、
  まとめて渡すと後ろの県が薄くなる）。

  **ざっと見るは軽い回**で、各県を 1 回で通り抜ける（足止めしない）。**情報収集は重い回**で、
  ざっと見るが見終えた県から、代表店未定が残る県には次の回も戻りながら粘る。かつては
  整理（直す）と情報収集（足すだけ）の 2 本だったが、どちらも代表店を探して足してもいて、
  重い相手にしか任せられない仕事だったので 1 本にした。
  """
  def sweeps do
    [
      %{
        name: @roster_sweep,
        interval_minutes: @roster_minutes,
        use_extract: true,
        # **足すだけ**。AI が肉付けしたぶんを、記事の冒頭しか持たない名簿で上書きしない
        only_new: true,
        once: true
      },
      %{
        name: @scan_sweep,
        prompt: :scan,
        interval_minutes: SweepNames.scan_minutes(),
        partitions_per_run: 1,
        after: @roster_sweep,
        # **一周したら止まる**。手の付いていないものを一通り片付けたら用が済む（そのあとは
        # 情報収集）。**足止めはしない** —— 軽い相手は 1 回に数件しか代表店を決めず、同じ県に
        # 何度戻っても進まなかった。各県を 1 回で通り抜け、残りは情報収集が粘る
        one_lap: true
      },
      %{
        name: @survey_sweep,
        prompt: :survey,
        interval_minutes: SweepNames.tidy_minutes(),
        partitions_per_run: 1,
        # **ざっと見るが見終えた県から回る**（`after_each`。一周は待たない）。名簿に混ざった
        # 料理でないもの・どこにでもある料理を外す前に回ると、その並びを手本に同じものを足してくる
        after: @scan_sweep,
        after_each: true,
        # **代表店未定が残る県は見終わったことにしない**（次の回もその県に戻る）。1 回に
        # 決めるのは料理 20 品までなので、印を付けて次の県へ進むと、残りは一周先になる。
        # その回に 1 品も減らなければ Chiezo が見終わりにして次へ進む（歯止め）
        hold_tag: @unplaced_tag,
        # **Chiezo の時計では回さない**（重い回なので、Chidori が時刻を決めて起こす。
        # `Chidori.Datasets.SurveyClock`）
        by_caller: true
      }
    ]
  end

  @doc "Chiezo へ送る依頼の中身（作るときも、送り直すときも同じもの）。"
  def attrs(choices \\ %{}) do
    %{
      name: @collection,
      # 収集の依頼文は情報収集のもの（割り込み・travel-log からの依頼もこの文で走る）
      prompt: survey_prompt(),
      interval_minutes: SweepNames.tidy_minutes(),
      sweeps: with_choices(sweeps(), choices),
      kind: "stock",
      resolve: resolve(),
      formats: formats(),
      locked_doubt_tag: @doubt_tag,
      # **一覧の 1 行に、空いている脇書きを添えてもらう**（Chiezo の `show_blanks`）。一覧は
      # 見出し・タグ・本文だけなので、空欄を埋める段を頼んでも AI にはどれが空か見えず、
      # 1 件も埋めずに終えた。提供の月（通年なら書かない）と市区町村（県全体の料理なら
      # 書かない）は空が正しい 1 件も多いので載せない
      show_blanks: @blank_keys,
      # 出典の URL を Chiezo に開いて確かめさせる（開けない頁を説明に書かない）
      links: true,
      requested_by: "chidori"
    }
    |> Map.merge(shape())
  end

  @doc "説明・名簿の指定・区画（画面の「区画の割り方」もここから読む）。"
  def shape do
    %{
      description: "Chidori のデータ収集（ご当地グルメ / travel-log 向け）",
      extract: extract(),
      partition: partition()
    }
  end

  # 画面で選んだ相手を巡回に載せる（`Chidori.Datasets.Dining` と同じ。Chidori は覚えない）
  defp with_choices(sweeps, choices) do
    for sweep <- Enum.map(sweeps, &resolve_prompt/1) do
      case Map.get(choices, sweep.name) do
        nil -> sweep
        picked -> Map.merge(sweep, Map.reject(picked, fn {_k, v} -> is_nil(v) end))
      end
    end
  end

  defp resolve_prompt(%{prompt: :survey} = sweep), do: %{sweep | prompt: survey_prompt()}
  defp resolve_prompt(%{prompt: :scan} = sweep), do: %{sweep | prompt: scan_prompt()}
  defp resolve_prompt(sweep), do: sweep

  @doc """
  情報収集の依頼文。**整理しつつ足りない情報を探す 1 本**で、1 県を受け持ち、次の順に進める
  （上ほど大事）。かつては整理（直す）と情報収集（足すだけ）の 2 本に分けていたが、どちらも
