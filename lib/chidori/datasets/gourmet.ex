      "#{genre_tag()}:フルーツ"）
    - **上に並んでいる料理の見出しでは返さないでください**（直すとき以外）。この回は直す回で、
      返した 1 件で中身が丸ごと置き換わります。足すのは上に無い見出しだけです
    - 3〜5 が残っている回は、この 6 はしないでください

    **4〜6 は全部でなくて構いません。** 見直せなかった料理は申告しないでください
    （`not_reviewed` に入れない）。

    #{ending_rule()}

    #{scope_rule()}

    #{shop_item_rule()}

    #{item_format()}

    **直した料理・消す料理・足す料理だけを返してください。** 直すところが無かった料理は
    返さなくて構いません（そのまま残ります）。

    **何を調べたかを、答えの `checked` に 1 行ずつ書いてください**（items と並べて
    `"checked": ["…", "…"]`）。例: "ソースカツ丼: 本店の公式メニューで提供を確認、代表店を本店に"、
    "見直し: 5 品の代表店の頁を確認、変更なし"。地図には載りません。
    """
  end

  @doc """
  ざっと見るの依頼文。**名簿から入った料理を一通り確かめ、すぐ分かる代表店だけを決める**。
  2 時間おきに 1 県ずつ回して一周で止まり、足止めはしない（`sweeps/0`）。調べ込む代表店・
  見直し・足りないものを足す・travel-log からの報告は情報収集の仕事。軽い相手は 1 回に数件しか
  代表店を決めず、同じ県に何度戻っても進まなかったので、各県を 1 回で通り抜けて情報収集へ渡す。
  **すぐ分かる代表店は決める** —— 決めないと、ざっと見るが終わっても地図に何も出ない。

  **空欄を埋める段（3）は飛ばさないよう強く頼む** —— 「全部でなくて構いません」と書いた
  頃は、軽い相手が名簿の確認と代表店だけで終え、空欄をほとんど埋めなかった（1 県で
  代表店の理由が空のもの 122 件が残ったまま）。

  **代表店の段（2）も同じく、時間の制限が無いことを書いて逃げ道を外す** —— 「時間が尽きたら
  そこまでで構いません」と書いていた頃は、軽い相手が名簿から入ったばかりの 54 件の県で、
  道具を 1 度も使わずに全部を `not_reviewed` で返した回と、種類のタグだけ直して代表店を
  1 つも決めなかった回が続き、代表店が決まらないまま県を抜けた。

  段の文は情報収集と同じもの（書き分けると、片方が直したものをもう片方が戻す）。
  """
  def scan_prompt do
    """
    #{prompt_head()}

    **この回は、まだ手の付いていないものを一通り見る回です。** 調べ込むのは別の回（情報収集）が
    します。**この県の名簿を 1 で全部見て、2 はすぐ分かる代表店だけ、3 は見れば分かる空欄だけ**
