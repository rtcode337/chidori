    佐賀県 長崎県 熊本県 大分県 宮崎県 鹿児島県 沖縄県
  )

  # 1 周目を回り始める県（JIS の番号。13 = 東京都）。ここから番号順に沖縄県まで行き、
  # 北海道に戻って 12（千葉県）で一周する
  @first_prefecture 13

  # 名簿に入れるカテゴリの括り（`<県の名前>の<括り>`）。**県の名前が付いているものだけ**。
  # 「日本の郷土料理」「ご当地グルメ」のような全国の括りは単独では入れない —— 名前から県が
  # 読めないうえ、カツ丼・おでんのようなどこにでもある料理が混ざる（前の作り方で
  # 「一般的な料理」が多く入った原因。県の食文化との組でだけ入れる。下の `@national_kinds`）。地方の括り（関東地方のご当地ラーメン・
  # 東北地方の駅弁など）も県が読めないので入れない。地方のご当地ラーメンの記事は
  # ほとんど（108 件中 106 件）が県の麺料理にも入っているので、そちらから入る。
  #
  # 本番の Chiezo の `/v1/jawiki/tags?contains=` で実在と件数を確かめてある（2026-10）:
  # 「<県>の麺料理」47 県・のべ 372 件、「<県>の土産菓子」44 県・のべ 394 件、北海道だけにある
  # 「北海道のご当地ラーメン」19・「…ご当地焼きそば」9・「…ご当地カレー」14・
  # 「…ご当地丼」8・「北海道の駅弁」6。**47 県ぶんを組み立てて渡す**（無い県の名前は
  # 0 件で終わる）—— 書き並べると、あとから県のカテゴリが増えたときに黙って落ちる。
  #
  # 「<県>の食文化」「<県>の菓子」は単独では入れない。食文化は企業・番組・人物・動植物まで
  # 抱えていて（前の作り方で 1,007 件のうち 6 割を落とした）、菓子はかき氷・鰹節のような
  # 土地に紐づかない食品まで入る（食文化は、農業と全国の括りとの組でだけ使う。下）
  @roster_kinds ~w(麺料理 土産菓子 ご当地ラーメン ご当地焼きそば ご当地カレー ご当地丼 駅弁)

  # **店の括り**（`<県>の飲食店`）。県の名前が付いた飲食店のカテゴリで、記事のある店
  # （百科事典に記事があること自体を知名度の目安にする）が県ごとに入っている。本番の
  # Chiezo の `/v1/jawiki/tags?contains=飲食店` で確かめた（2026-10）: 39 県に実在し
  # （秋田県・香川県・鹿児島県など 8 県には無い）、東京都 128・神奈川県 39・大阪府 29・
  # 愛知県 28 …、のべ 368 記事。
  # 店は料理の括りにも入っている（「ラーメン店」かつ「<県>の麺料理」が 22 件 —— ラーメン二郎・
  # ホープ軒・中華蕎麦とみ田…、和菓子の店が県の土産菓子に 26 件）
  @shop_kind "飲食店"

  # **店の記事の印**（どれかが付いていれば「区分:店」）。名簿の括りに入った記事のうち、
  # 店の種類のカテゴリか `<県>の飲食店` を持つもの。料理の記事に付いていないことを
  # 本番の名簿の候補で確かめてある（「鰻料理」は うなぎパイ のような料理にも付くので使わない）。
  # 漏れは整理の回が直す（印の付け外しは AI に頼む）
  @shop_categories ~w(ラーメン店 餃子店 洋菓子店 菓子店 パン店 和菓子の店舗・メーカー 日本の外食事業者 うどん・蕎麦屋 寿司屋)

  # **店の種類のカテゴリだけで入る記事は、市区町村の付いた括り（か県の食文化）も持つものだけ**
  # （Chiezo の抽出の `tag_pairs`）。店の種類のカテゴリは全国の括りで県が読めない ——
  # 県の飲食店に入っていない店（六厘舎・壱発ラーメン…）は名簿に入っていなかった。
  # 県は市区町村の名前から地図辞典で読む（`area_of`）
  @shop_city_pattern "^(.+?[市区町村](?: \\(.+\\))?)の(?:企業|建築物|食文化)$"

  # **組で入れる括り**（`<県>の農業` で、同じ県の `<県>の食文化` にも入っている記事だけ）。
  # 農業のカテゴリは農協・試験場・品種・制度まで抱えるが、食文化にも入っている記事は
  # その土地の名産の農産物・ブランド牛・茶がよく拾える（本番の Chiezo で 2026-10 に
  # 確かめた: 47 県のべ 410 件、うち米の品種 47 件。神奈川県 20 件 = 湘南ゴールド・
  # 三浦大根・足柄茶…、群馬県 14 件 = 下仁田ネギ・国府白菜…）。Chiezo の抽出の
  # `tag_pairs`（同じ県どうしの組でしか採らない）。種類は「食材」
  @paired_kind "農業"
  @paired_with "食文化"

  # **組で入れる全国の括り**（県の名前が付かない括りで、**どこかの県の `<県>の食文化` にも
  # 入っている記事だけ**）。全国の括りは県が読めず、どこにでもある料理も混ざるので単独では
  # 入れないが、県の食文化にも入っている記事は、その県の郷土料理・水産加工品・鍋がよく拾える。
  # **県はその食文化のタグから読む**（2 県以上なら `split` で県ごとに分かれ、整理が 1 県に
  # まとめるか県ごとに残すかを決める）。本番の Chiezo の `filter` で数えた（2026-10。
  # 全体 → 県の食文化にも入っている記事）: 日本の郷土料理 364 → 265（きりたんぽ・冷や汁・
  # 鰹のタタキ・五平餅…）、日本の水産加工品 108 → 61（くさや・カラスミ・鮒寿司・鮭とば）、
  # 日本の鍋料理 74 → 48（ちゃんこ鍋・芋煮会・水炊き・もつ鍋）、日本の発酵食品 38 → 25
  # （へしこ・しょっつる・酒盗）、農山漁村の郷土料理百選 92 → 55。重なりを畳んで 371 記事、
  # 外す括りと今の名簿の重なり（6 記事）を除いて 365 記事・県ごとに分けて約 500 件増える。
  # Chiezo の抽出の `tag_pairs` の `with_pattern`（相手を「どれかの県の食文化」で書く）
  @national_kinds ~w(日本の郷土料理 日本の水産加工品 日本の鍋料理 日本の発酵食品 農山漁村の郷土料理百選)

  # 名簿から外すカテゴリ（どれか 1 つでも付いている記事は入れない）。**会社・メーカー・
  # 商品・作品・店でないもの・閉じた店**を落とす —— 県の麺料理には即席麺の商品やメーカーが、
