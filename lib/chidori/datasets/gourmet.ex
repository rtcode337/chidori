  # 名簿から機械で入った料理を確かめる段（`n` は段の番号）
  defp roster_step(n) do
    """
    **#{n}. 名簿から機械で入った料理を確かめる。** tags に "#{Chiezo.unreviewed_tag()}" が
    付いている料理は、百科事典のカテゴリから機械で入れたもので、まだ誰も見ていません。
    次のものは墓標で消してください（body に理由を 1 行）:
    料理・食品でも店でもないもの（会社・団体・番組・大会・一覧や総称の記事。「京料理」
    「沖縄料理」のような土地の料理全体の記事も総称）、
    **この県のご当地と言えない、どこにでもある料理**（「素麺」「鍋焼きうどん」のような一般名）、
    **終わったもの**。一般名の食材は下の「一般名の食材」の決まりで判断してください。
