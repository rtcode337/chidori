  # 愛知県 28 …、のべ 368 記事。
  # 店は料理の括りにも入っている（「ラーメン店」かつ「<県>の麺料理」が 22 件 —— ラーメン二郎・
  # ホープ軒・中華蕎麦とみ田…、和菓子の店が県の土産菓子に 26 件）
  @shop_kind "飲食店"

