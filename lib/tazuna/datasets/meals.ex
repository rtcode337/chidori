defmodule Tazuna.Datasets.Meals do
  @moduledoc """
  食事処 —— travel-log の地図に並べる「食べに行く先」を Chiezo に集めさせる依頼です。

  **網羅の収集**です。ある括りの全部が対象で、増減はしても古いものが要らなくなる
  ことはない —— ニュースのように期限で落とすと、地図に穴が開きます。

  ## 名簿は 3 つの辞典から機械で引きます

  名前・座標・住所・電話・サイト・紹介文は、Chiezo の百科事典（`jawiki`）・
  地図辞典（`osm_japan`）・店舗辞典（`overture_japan`）に入っています。
  **AI に書かせません** —— 座標を書かせると当てにならない値が混ざり、しかも実行の
  たびに違う値になります。AI に頼むのは、そこに書いていないこと（これは食べに行く
  先か・まだ開いているか・どう紹介するか）だけです。

  **どの項目をどこから採るかは決めてあります**（`extract/0`）。座標は地図辞典、
  説明は百科事典、店舗辞典はいちばん低く —— 同じ店が複数の辞典に居たときに、
  そのつど違う値が入らないようにするためです。

  **どの辞典も絞りません。** 網羅の収集なので、機械で引けるものを取りこぼすと、
  そのぶんを巡回が区画ごとに探し直すことになります —— **機械で済む仕事を AI に
  払わせる**形です。店舗辞典を上位 2 万件で切っていた頃は 41 万件の 5% しか
  採れておらず、触れ込みと中身が食い違っていました。

  ## 大きさの目安

  | | |
  |---|---|
  | 名簿 | 約 52 万件（百科事典 900 + 地図辞典 10 万 + 店舗辞典 41 万） |
  | 区画 | 約 3,470（1 区画 150 件） |
  | Chiezo の素材 | 約 130 MB（1 件 256 バイト） |
  | 取り込み時のメモリ | 1.6 GB 前後。**前世代も同時に載るので定常では倍を見る** |

  ## 区画は座標で割ります

  **母集団は自分自身**（集めたものの座標）で、bbox に日本全体を書いてあります。
  外のソースを母集団にすると区画は動かないので楽ですが、**割り直しが効かなくなります**
  —— Chiezo が区画を割り直すのは、自分自身を割っているときだけです
  （育って `target` を超えた区画と、空になった区画が引き金）。座標が直れば区画も
  それに追随してほしいので、こちらを採ります。

  **bbox を書くのは、まだ 1 軒も入っていない範囲を対象から落とさないため**です。
  点から矩形を作ると、点の無いところは矩形の外になり、「ここに足りない店はないか」を
  永遠に問えません。

  ## 巡回は 3 本

  | 巡回 | やること | AI |
  |---|---|---|
  | 名簿 | 3 つの辞典から機械的に引く | 使わない |
  | ざっと | 区画を一周して、座標を直し・閉店を消し・中身を埋める | 使う |
  | じっくり | 区画ごとに、**足りない店を足す**（ついでに精査も） | 使う |

  **順番に意味があります。** じっくりはざっとが一周するまで走りません（`after`）——
  座標の直っていない状態で「この区画に足りないもの」を問うても、その店は
  別の区画に居るだけなので、既に入っているものを挙げて終わります。

  **一周の長さは、区画の大きさではなく件数で決まります。** AI は 1 件あたり約 1.1 秒
  （実測）で、区画ごとに 1 回ずつ直列に聞きます。区画を大きくして減るのは 1 回ごとの
  定型文の無駄だけで、**一周は縮みません**。

  **何日で一周するかは、ここでは決め打ちしません。** 巡回に書く日数は希望で、
  実際の速さは**区画の数**と**Chiezo が 1 回に見る区画の上限**で決まります ——
  区画が増えれば伸び、上限に当たれば書いた日数には届きません。
  **いま何日かかるかは Chiezo の画面**（収集の面の巡回の表）が出します。
  ざっとは一周したら止まるので、費用は立ち上げの一度きりです。
  """

  alias Tazuna.Chiezo

  @collection "tazuna_meals"

  # 対象の矩形。**日本全体**（`[南緯, 西経, 北緯, 東経]` = Chiezo の順）。
  # 書かないと母集団の外接矩形になり、まだ 1 軒も入っていない範囲が対象から落ちる
  @japan_bbox [20.2, 122.5, 45.8, 154.0]

  # 巡回を広げ始める 1 点（東京駅）。**書かないと南西の隅から北上します** ——
  # 矩形の鍵は角から並ぶので、日本の地図では八重山が最初になる。一周に何十日も
  # かかる台帳では、店の多いところに着くのが何か月も先になる
  # （実測: 10,457 区画・1 回 5 区画・1 時間おきで一周 87 日）。
  # **2 周目からは何もしなくてよい** —— 1 周目を近い順に回れば印も近い順に付くので、
  # Chiezo の「古い順」がそのまま同じ広がり方をなぞる
  @start_from [35.681, 139.767]

  # 1 区画あたりの目安。**Chiezo が 1 回に差し込めるぶんに収まる大きさ**にする ——
  # 超えると `{current}` が切られ、切られたぶんは「今回の対象外」になって、
  # 漏れを問う前提（この範囲の全部が並んでいる）が崩れる。
  #
  # **見るのは入り口より出口。** 差し込みの枠（件数 300 件・文字数 8 万文字）より
  # 先に、**AI が返せる量**が効く —— この回は残す店ぜんぶにタグと紹介文を付けさせる
  # ので、区画の件数がそのまま返る件数になる。
  #
  # 実測（Antigravity に 150 件ぶんを返させた）: **150 件が切れずに全部返り**、
  # 47,685 文字・2 分 50 秒。1 件あたり約 318 文字・約 1.1 秒。
  # 1 回の持ち時間は 840 秒（CLI ブリッジの上限）なので時間にはまだ余裕があるが、
  # **1 回の取り込みは区画を 20 まで直列に回す**ので、そちらが先に長くなる。
  #
  # **大きくしても一周は縮まない。** 同じ店を同じだけ読ませるので、一周の長さは
  # 件数 × 1.1 秒で決まる（52 万件なら、AI を回し続けても 6.6 日が下限）。
  # 大きくして減るのは 1 回ごとの定型文の無駄で、増えるのは切れる危険のほう
  @partition_target 150

  # 名簿を引き直す間隔。**週 1 で足りる** —— 地図辞典が焼き直されるのはその程度で、
  # AI を呼ばないぶん頻度を上げても得るものが無い
  @roster_minutes 10_080

  # ざっと。**一周したら止まる** —— 座標と閉店を一度ずつ見れば用が済む回で、
  # 止めないと 2 周目 3 周目が同じことを聞くために枠を使う。
  #
  # **日数は希望であって、約束ではありません。** Chiezo は 1 回に見る区画の数に
  # 上限を持っていて（区画ごとに AI を 1 回、直列に呼ぶので、1 回の取り込みが
  # 何十分にもなる）、**区画が多いとそこで頭打ちになります** —— 書いた日数より
  # 遅くなるので、ここに短い日数を書いても速くはなりません。
  # **実際にかかる日数は Chiezo の画面が出します**（そのときの区画数から計算する）。
  # 間隔のほうは意味があります: 1 回の取り込みが次の予定に追いつかれない長さにする
  @scan_minutes 60
  @scan_days 15

  # じっくり。**ざっとと同じ速さで回す**（1 時間ごと）。
  #
  # 6 時間ごとにしていた頃は、**区画の数に対して一周が現実的でありませんでした** ——
  # 1 回に見られる区画には上限があるので、間隔を空けたぶんだけ一周が延びます。
  # この回は「足りない店を足す」のが主な仕事で、**足りないままの区画が何か月も
  # 放っておかれる**のがいちばん困ります。
  #
  # 日数は希望で、上限に当たればそこで頭打ちになる（ざっとと同じ）
  @survey_minutes 60
  @survey_days 15

  # 割り込みを頼む先。**専用の 1 本は置かない**（頼むのは同じ仕事なので、
  # 設定も依頼文もじっくりのものでよい）
  @survey_sweep "整理"

  # ざっとの名前。**区画を回るのはこの回が先** —— じっくりはざっとが一周するまで
  # 走らないので、進み具合を「じっくりが見たか」で測ると、いつまでも 0 のままになる
  @scan_sweep "ざっと見る"

  # 出典の目印。**travel-log と AI の両方が読む** —— 同じ店が 2 つに分かれているとき、
  # どちらの座標を残すかはここで決まる（1 軒に複数付くこともある）
  @source_tags [wikipedia: "出典:Wikipedia", osm: "出典:OSM", overture: "出典:Overture"]

  # 百科事典の飲食店カテゴリ。**都道府県ごとに分かれている**ので末尾で指す
  # （書き並べると、あとから県が増えたときに黙って落ちる）
  @wiki_suffix "の飲食店"
  @wiki_tags "日本のレストラン,ラーメン店"

  # 百科事典から外すカテゴリ。**チェーンは地図の邪魔になる**（どこにでもある）
  @wiki_excluded "レストランチェーン"

  # 地図辞典（OSM）で食事処に当たる地物。**喫茶店やファストフードは採らない**
  @osm_feature "amenity=restaurant"

  # 名簿に引く地図辞典のカテゴリ。**食べに行く先だけ**を採る。
  # カテゴリ名は Overture のもので、推測で書くと**エラーにならず 0 件**になる
  # （`/v1/overture_japan/tags?contains=` で実在を確かめてある）
  @categories ~w(
    restaurant japanese_restaurant sushi_restaurant noodles_restaurant
    barbecue_restaurant seafood_restaurant chinese_restaurant korean_restaurant
    italian_restaurant french_restaurant
  )

  # 名簿から外すカテゴリ。**チェーンのファストフードは地図の邪魔になる**ので、
  # 同じ地物に付いていたら名簿ごと落とす（残すかは AI ではなくここで決める）
  @excluded ~w(fast_food_restaurant burger_restaurant pizza_restaurant)

  # 地図辞典のカテゴリ → 日本語のジャンル。**travel-log のシリーズになる**ので、
  # AI ではなく機械で付ける（実行のたびに揺れない）。
  #
  # **細かいものを先に並べる。** 読み替えは書いた順にタグを作り、travel-log は
  # 先頭のものをシリーズに使う —— 1 軒には何段階かのカテゴリが同時に付いている
  # （寿司屋には「寿司」と「和食」の両方）ので、粗いほうが先にあると、
  # 地図はどの店も同じ一語で埋まる。
  #
  # **カテゴリ名は実在を確かめてから足す。** 推測で書いてもエラーにならず、
  # その読み替えが一度も当たらないまま静かに残る
  # （`/v1/overture_japan/tags?contains=` で引ける）
  @genres [
    {"sushi_restaurant", "寿司"},
    {"noodles_restaurant", "麺類"},
    {"barbecue_restaurant", "焼肉"},
    {"seafood_restaurant", "海鮮"},
    {"chicken_restaurant", "鶏料理"},
    {"steakhouse", "ステーキ"},
    {"korean_restaurant", "韓国料理"},
    {"chinese_restaurant", "中華"},
    {"italian_restaurant", "イタリアン"},
    {"french_restaurant", "フレンチ"},
    {"indian_restaurant", "インド料理"},
    {"thai_restaurant", "タイ料理"},
    # **いちばん粗いものを最後に。** 上のどれにも当たらなかった和の店がここに落ちる
    {"japanese_restaurant", "和食"}
  ]

  @doc "この収集の目印のタグ。**travel-log はこれで 1 件を拾います**。"
  def kind_tag, do: "食事処"

  @doc "ジャンル。**先頭が travel-log のシリーズ**で、残りはカテゴリに回せます。"
  def genre_tag, do: "ジャンル"

  @doc "都道府県。travel-log の `region` に当たります。"
  def area_tag, do: "地域"

  @doc "知名度の段階（A〜E）。travel-log の `rank` に当たります。"
  def rank_tag, do: "ランク"

  @doc """
  溜め先の収集の名前（= Chiezo のソース名）。`TAZUNA_MEALS_COLLECTION` で変えられます。

  **後から変えない** —— 変えると、それまで溜めた先を見失います。
  """
  def collection do
    case System.get_env("TAZUNA_MEALS_COLLECTION", "") |> String.trim() do
      "" -> @collection
      name -> name
    end
  end

