  @doc """
  名簿の引き方（Chiezo の「抽出の指定」）。**tazuna が持ちます**。

  中身が travel-log に渡す項目そのもの（座標・住所・サイト・ジャンル）なので、
  向こうに預けると、読む側と引く側が別々に動いて静かにズレます。

  ## 3 つのソースから引きます

  ひとつの辞典だけでは、要る項目が揃いません。**それぞれ得意なところが違う**ので、
  同じ見出しが複数に居たときに**どの項目をどこから採るか**まで書いてあります
  （Chiezo の `provides`）。

  | ソース | 件数 | 勝つ項目 | なぜ |
  |---|---|---|---|
  | 百科事典（`jawiki`） | 約 900 | 説明・出典 | **読み物になる紹介文があるのはここだけ** |
  | 地図辞典（`osm_japan`） | 約 10 万 | 座標・住所・サイト | 現地を歩いた人が置いた点で、いちばん確か |
  | 店舗辞典（`overture_japan`） | 上位 2 万 | （何も勝たない） | 件数はいちばん多いが、値の確かさは上の 2 つに劣る |

  **順位を譲ることと、その値を捨てることは別です。** 百科事典は座標で勝ちませんが、
  地図に載っていない 1 軒の座標はそこにしか無い —— 捨てると、**その 1 軒はどの区画にも
  入らず、AI から永遠に見えなくなります**（区画は座標で決まります）。Chiezo は
  勝った本で埋めたあと、空いたところを残りの本で埋めます。

  **見出しが違えば畳めません。** 実測では、同じ範囲の地図辞典と店舗辞典で名前が
  一致するのは 3%（60m 以内という条件を足しても 2〜9%）。**畳めなかったぶんは
  別の 1 件として並びます** —— 同じ店が 2 つあることに気づけるのは、区画をまとめて
  見る AI の回のほうなので、そちらに頼んであります。
  一方、**百科事典の見出しは地図辞典とよく一致します**（東京都の飲食店 128 件のうち
  地図辞典に 47 件・店舗辞典に 72 件）。紹介文が要るのはまさにそこなので、
  この形がいちばん効きます。
  """
  def extract, do: [wikipedia_extract(), osm_extract(), overture_extract()]

  # 百科事典。**説明で勝つ**（読み物になる紹介文があるのはここだけ）。
  # 座標も持っているが譲る —— 地図辞典のほうが確かなため
  defp wikipedia_extract do
    %{
      source: "jawiki",
      tag: @wiki_tags,
      tag_suffix: @wiki_suffix,
      not_tag: @wiki_excluded,
      provides: ~w(body url),
      # 記事の冒頭。**何の店で何が名物か**が 1〜2 文で書いてある
      body: "opening",
      url: "https://ja.wikipedia.org/wiki/{title}",
      tags: [
        %{const: kind_tag()},
        %{const: @source_tags[:wikipedia]},
        # **都道府県で終わるものだけを地域にする。** 「の飲食店」で終わる
        # カテゴリには「2021年開業の飲食店」のような年のものが混ざっていて、
        # そのまま採ると「地域:2021年開業」ができる
        %{pattern: "^(.+[都道府県])#{@wiki_suffix}$", format: "#{area_tag()}:{1}"},
        %{pattern: "^寿司屋$", format: "#{genre_tag()}:寿司"},
        %{pattern: "^ラーメン店$", format: "#{genre_tag()}:麺類"}
      ],
      # **知名度はここにしか無い。** ランクを AI に決めさせる材料になる
      extra: ~w(lat lon pageviews_month image)
    }
  end

  # 地図辞典。**座標で勝つ**（現地を歩いた人が置いた点）。
  # **件数を書かない** —— 書くと見出し順で切られる。OSM は飲食店にどれも同じ点しか
  # 付けないので、`rank_score` が並びを決めず、名前が先に来るものだけが残る
  defp osm_extract do
    %{
      source: "osm_japan",
      tag: @osm_feature,
      provides: ~w(extra),
      body: "opening",
      # `area` は都道府県。**travel-log の地域が機械で決まる**
      extra: ~w(lat lon area address website phone wikidata),
      tags: [%{const: kind_tag()}, %{const: @source_tags[:osm]}]
    }
  end

  # 店舗辞典。**何も勝ちにいかない**（件数はいちばん多いが、値の確かさは劣る）。
  # 上の 2 つが埋めなかったところだけを埋める
  defp overture_extract do
    %{
      source: "overture_japan",
      tag: Enum.join(@categories, ","),
      not_tag: Enum.join(@excluded, ","),
      provides: [],
      # **件数は書かない（全部採る）。** 飲食店のカテゴリは 41 万件あるが、
      # ここで切ると網羅にならない —— 2 万件で切っていた頃は 5% しか採れておらず、
      # 「日本の食事処を全部集める」という収集の触れ込みと食い違っていた。
      # 切り口に意味がある（`confidence` の順）としても、**採らなかった 95% は
      # 巡回が区画ごとに探し直すことになり、機械で引けるものを AI に払わせる**
      # 名前・種別・所在・住所・座標が 1 段落に入っている。
      # **AI に見せるのはこの本文**なので、座標の食い違いはここから読み取れる
      body: "opening",
      tags:
        [%{const: kind_tag()}, %{const: @source_tags[:overture]}] ++
          for {category, genre} <- @genres do
            %{pattern: "^#{category}$", format: "#{genre_tag()}:#{genre}"}
          end,
      # **元の地物に書いてある事実は、そのまま運ぶ。** travel-log が要るのはここ ——
      # 読む側が 1 件ずつ地図辞典を引き直さずに済む
      extra: ~w(lat lon address locality website phone confidence)
    }
  end

  @doc "出典の目印。**1 軒に複数付くことがあります**（複数のソースに居た店）。"
  def source_tags, do: Keyword.values(@source_tags)

  @doc """
  出典タグの前置き。書き出し（`Tazuna.Datasets.TravelLog`）が、どの辞典から来たかを
  説明文に写すのに使います。**辞典ごとにライセンスが違う**ので、渡した先で
  切り分けられるようにしておく必要があります。
  """
  def source_tag_prefix, do: "出典"

  @doc """
  区画の割り方。**座標で、密なところは細かく、疎なところは粗く**（k-d 木と同じ割り方）。

  母集団を書かないのは、**自分自身を割っているときだけ Chiezo が割り直す**ためです。

  **どこから広げるかも渡します**（`origin`）。書かないと鍵の文字列順、つまり
  南西の隅からになります。
  """
  def partition do
    %{by: "geo", target: @partition_target, bbox: @japan_bbox, origin: @start_from}
  end

  @doc """
  巡回 3 本。**仕事が違うものは 1 本にまとめません** ——
  1 つの文で全部を頼むと、どの回も同じ薄さの仕事になります。
  """
  def sweeps do
    [
      # **機械で引く回。** AI を呼ばず、抽出の指定を走らせるだけ。
      # **一度きり** —— 地図辞典が焼き直されない限り何度やっても同じで、
      # その 1 回ぶんの取り込みが無駄になる（焼き直したら押して走らせる）。
      # **足すだけ**（`only_new`）にしないと、AI が肉付けしたぶんを
      # 名前と住所しか持たない名簿で上書きする
      %{
        name: "機械収集",
        interval_minutes: @roster_minutes,
        use_extract: true,
        only_new: true,
        once: true
      },
      %{
        name: @scan_sweep,
        interval_minutes: @scan_minutes,
        cover_days: @scan_days,
        after: "機械収集",
        one_lap: true
      },
      %{
        name: @survey_sweep,
        prompt: :survey,
        interval_minutes: @survey_minutes,
        cover_days: @survey_days,
        after: @scan_sweep
      }
    ]
  end

  @doc """
  Chiezo へ送る依頼の中身（作るときも、送り直すときも同じもの）。
  """
  def attrs(choices \\ %{}) do
    %{
      name: collection(),
      description: "tazuna のデータ収集（日本の食事処 / travel-log 向け）",
      prompt: scan_prompt(),
      interval_minutes: @scan_minutes,
      extract: extract(),
      partition: partition(),
      sweeps: with_choices(sweeps(), choices),
      # **網羅。** ある括りの全部が対象で、古いものが要らなくなることはない
      kind: "stock",
      requested_by: "tazuna"
    }
  end

  # 画面で選んだ相手を巡回に載せる。**tazuna は覚えない** —— 正は Chiezo が
  # 持っているもので、画面はそれを読んで見せているだけ
  defp with_choices(sweeps, choices) do
    for sweep <- Enum.map(sweeps, &resolve_prompt/1) do
      case Map.get(choices, sweep.name) do
        # **空文字は落とさない。** あれは「Chiezo の既定にまかせる」を選んだという
        # 意思表示で、落とすと一度決めた相手を外せなくなる
        nil -> sweep
        picked -> Map.merge(sweep, Map.reject(picked, fn {_k, v} -> is_nil(v) end))
      end
    end
  end

  # 巡回ごとの依頼文。**定義の中では名前で置いてある** —— 依頼文は数十行あるので、
  # 巡回の一覧に直に書くと、どの巡回がどんな設定かが読めなくなる
  defp resolve_prompt(%{prompt: :survey} = sweep), do: %{sweep | prompt: survey_prompt()}
  defp resolve_prompt(sweep), do: sweep

  @doc """
  ざっとの依頼文。**この回は、入っているものを直す回**です。

  足すことは頼みません —— 名簿は地図辞典から機械で引いた下地なので、まず
  「この区画に並んでいるものが正しいか」を一周ぶん確かめるほうが先です。
  """
  def scan_prompt do
    """
    日本の「食事処」の一覧を、**この区画ぶんだけ見直してください**。
    travel-log という地図アプリのスポットとして使います。

    **今回見る範囲**
    {partition}

    {current}

    **上に並んでいるのが、この範囲の全部です。** 名簿は 3 つの辞典
    （Wikipedia・OpenStreetMap・Overture Maps）から機械的に作ってあり、
    1 件ごとに**どこから来たかのタグ**が付いています。
    **この回にやってほしいことは 4 つ**です。

    **1. 座標を直す。** 本文の「座標:」が、その店の所在地と食い違っていないかを
    確かめてください。**間違っているものだけ**、正しい緯度・経度を `lat` と `lon` に
    数で入れて返します。**区画は座標で決まる**ので、ここがずれていると、その店は
    別の土地の区画に並び続けます。
    **確かめられなかったものは触らないでください** —— 書き換えると、正しかった座標が
    当てずっぽうの値に置き換わります。座標を触らない 1 件では `lat` / `lon` を
    書かなくて構いません（触れなかった値はそのまま残ります）。

    **座標が違うことは、消す理由ではありません。** 住所がこの範囲の外を指していても、
    **消さずに正しい座標へ直してください** —— 直せば次の回から本来の区画に並びます。
    消してしまうと、その店は名簿から消えたまま、どの区画にも戻ってきません。
    消すのは下の 2 つと、重複をまとめるときだけです。

    **2. 閉店したものを消す。** もう営業していない店は、墓標で消してください
    （tags に "#{Chiezo.tombstone_tag()}" を入れ、body に「◯年に閉店」のように
    理由を1行書く）。地図辞典は閉店をすぐには落とさないので、**ここは AI にしか
    見分けられないところ**です。

    **3. 食事処でないものを消す。** 名簿はカテゴリで機械的に作っているので、
    弁当屋・仕出し・社員食堂・カラオケ店のような「食べに行く先ではないもの」が
    混ざります。同じく墓標で消してください。

    **同じ店が 2 つに分かれていたら、1 つにまとめてください。** 辞典ごとに名前の
    書き方が違うので（「AFURI 新宿店」と「阿夫利 新宿」のように）、機械では畳めて
    いません。**ここは AI にしか見分けられないところ**です。
    残すほうに中身をまとめて返し、消すほうに墓標を付けてください。
    #{merge_rule()}

    **4. 中身を埋める。** 残すものには、下の形でタグと紹介文を付けてください。
    **とくに地域（都道府県）の空いているものは、必ず埋めてください** ——
    名簿の元になった店舗辞典は日本ではこの欄がほとんど空で、travel-log は
    都道府県の無いスポットを地図に置けません。本文の「住所:」と座標から分かります。

    **消す理由は必ず body に書いてください。** 消したものは名前が並ぶだけなので、
    理由が無いと消し間違いに気づけません。

    #{item_format()}

    **触ったものだけ返してください。** 触れなかったものはそのまま残ります。
    """
  end

  @doc """
  じっくりの依頼文。**主な仕事は「足りない店を足す」こと**で、精査はついでです。

  ざっとが一周したあと、この回がずっと回り続けます —— 名簿の元は地図辞典なので、
  **新しい店・小さい店・地図に載っていない店**は入っていません。そこを埋めるのが
  この層の値打ちで、**入っているものを磨くだけなら機械でもできます**。

  割り込み（「この区画を先に調べて」「この店が違う」）もここへ来ます。
  """
  def survey_prompt do
    """
    日本の「食事処」の一覧を、**この区画ぶんだけ仕上げてください**。
    travel-log という地図アプリのスポットとして使います。

    **今回見る範囲**
    {partition}

    {current}

    **上に並んでいるのが、この範囲の全部です。** やってほしいことは 2 つで、
    **1 つめが主な仕事**です。

    **1. 足りない店を足す。** この範囲にあって、上に並んでいない店を探してください。
    名簿の元は地図辞典（Overture Maps）なので、**新しい店・小さい店・地図に
    載っていない店**は入っていません。行列のできる店、地元で名の通った店、
    その土地の名物を出す店が、まるごと抜けていることがあります。
    **手元の知識サーバー（chiezo の MCP）を先に引いてください** ——
    レート制限が無く、入っている地物は実在が確かめられています。足りなければ web で。
    **確信が持てるものだけを挙げてください。** 思い当たらなければ足さなくて構いません
    —— 既にあるものを挙げ直しても名簿は変わらず、AI の枠だけが減ります。

    **足すものには必ず座標を入れてください**（`lat` と `lon` に数で）。
    **座標の無いものはどの区画にも入らず**、次に同じ区画を見たときには
    「まだ無い」と見えるので、同じ店を何度も足すことになります。

    **2. 並んでいるものを精査する。** 座標が所在地と食い違っていれば**直し**
    （**消さないでください** —— 直せば次の回から本来の区画に並びます）、
    閉店したもの・食べに行く先でないものは墓標で消し（tags に
    "#{Chiezo.tombstone_tag()}" を入れ、body に理由を1行）、
    説明・ジャンル・地域・ランクの空いているところを埋めてください。
    **地域（都道府県）だけは必ず埋めてください** —— 空のままだと travel-log は
    そのスポットを地図に置けません（本文の「住所:」と座標から分かります）。
    **同じ店が 2 つに分かれていたら 1 つにまとめてください**（辞典ごとに名前の
    書き方が違うので、機械では畳めていません）。
    **逆に、1 件に別々の店が混ざっていたら分けてください。** 名簿は**見出しで
    同じものかを決めている**ので、**同じ名前の別の店が 1 件に潰れている**ことが
    あります（本文は東京の店の説明なのに座標は熊本、のように食い違って見えます）。
    見分けたら、**片方を新しい見出しで足し**（店名のうしろに市区町村を添える。
    例「東京の洋食店 (熊本市北区)」）、元の 1 件はもう片方の内容に揃えてください。
    **確かめられなかったものは触らないでください** —— 疑わしいから消す、をやると、
    正しかったものまで落ちます。
    #{merge_rule()}

    #{item_format()}

    **触ったものと足すものだけ返してください。** 触れなかったものはそのまま残ります。
    """
  end

  # 同じ店が 2 つに分かれていたときの、どちらを採るかの決まり。
  # **2 つの依頼文で同じものを使う** —— 書き分けると、回によって別の値が残る。
  #
  # **機械で決められるところは機械で決めてある**（`extract/0` の `provides`）ので、
  # ここで言うのは**機械が畳めなかったぶん**の話。畳めていれば AI は 1 件しか見ない
  defp merge_rule do
    """
    **まとめるときは、出典のタグを見て決めてください。**

    - **座標は "#{@source_tags[:osm]}" の付いた側**を残す（現地を歩いた人が置いた点です）。
      無ければ "#{@source_tags[:wikipedia]}"、それも無ければ残ったほうで構いません
    - **説明は "#{@source_tags[:wikipedia]}" の付いた側**を残す（読み物になっているのはこちらです）
    - **電話・公式サイトは埋まっているほう**を残す
    - **出典のタグは、まとめた側にすべて残してください**（どの辞典に載っていた店かは、
      次に見るときの手がかりになります）
    """
  end

  # 1 件の形。**2 つの依頼文で同じものを使う** —— 書き分けると、片方だけ直したときに
  # 回によって別の形が返ってくる（travel-log が読むのはこの形）
  defp item_format do
    """
    1 件の形は次のとおりです。

    - title: **店の名前だけ**（地名や説明を混ぜない）。
      **同じ店は同じ表記で返してください** —— ここが同一の鍵で、変えると別の店として
      増えます。上に並んでいるものを直すときは、その表記のまま返してください
    - body: 1 行目に「所在地: 都道府県 市区町村 まで」、2 行目以降に
      **2〜3 文の紹介**（何が名物で、どういうときに寄る店か）。
      味の評価ではなく、**行くかどうかを決められること**を書いてください
    - url: 出典（店の公式サイトか、それに準ずるもの）
    - lat / lon: 緯度・経度を数で。**直すときと足すときだけ**書きます
    - tags: **いま付いているタグは、直すもの以外そのまま残してください**
      （返した内容で丸ごと置き換わるので、書かなかったタグは消えます）
      - "#{kind_tag()}" —— この一覧の目印。**必ず残してください**
      - "#{genre_tag()}:<ラーメン / 寿司 / 和食 のような料理の種類>"。
        **先頭のものが地図の見た目になる**ので、その店を一言で言うものを先に。
        当てはまるものが複数あれば並べて構いません
      - "#{area_tag()}:<東京都 / 京都府 のような都道府県>"。
        **空いているものは必ず埋めてください** —— travel-log の `region` に当たり、
        ここが無いスポットは地図に置けません。名簿の元の店舗辞典は、日本では
        この欄がほとんど空のまま入ってきます
      - "#{rank_tag()}:<A〜E>" —— **どれくらい知られているか**。
        A=全国から人が来る、B=その県を代表する、C=その市区町村で知られる、
        D=地元で親しまれている、E=それ以外。**地図の丸の大きさになります**ので、
        迷ったら下の段にしてください（全部が A だと、大きさが何も表さなくなります）
      - "#{Enum.join(source_tags(), ~s(" / "))}" —— **どの辞典から来たか**。
        機械が付けたものなので、**足したり消したりしないでください**
        （自分で見つけて足した 1 件には、どれも付けません）
    """
  end
end
