    申告すると、その店は AI がまだ見ていない扱いのまま地図に出ず、次の回でも同じく
    見つからないので、いつまでも残り続けます。

    **消す理由は必ず body に書いてください。** 消したものは名前が並ぶだけなので、
    理由が無いと消し間違いに気づけません。

    #{item_format()}

    **直した店・消す店・足す店だけを返してください。** 確かめて直すところが無かった店は
    返さなくて構いません（そのまま残ります）。
    """
  end

  @doc """
  じっくりの依頼文。**主な仕事は「足りない店を足す」こと**で、精査はついでです。

  **この回は手で回します。** Chiezo が依頼文をファイルに書き出すので、web の画面から
  使う AI（Gemini など）へ渡し、答えのファイルを読み込ませます —— 名簿の元は
  地図辞典なので、**新しい店・小さい店・地図に載っていない店**は入っていません。
  そこを埋めるのがこの層の値打ちで、**入っているものを磨くだけなら機械でもできます**。

  探すのは web を何度も引く仕事で、CLI ブリッジ越しの相手では 1 区画 6〜14 分
  かかりました（上限で切れることもあった）。画面から使う AI のほうが速く、
  こちらの枠も取り込みの番も使いません。

  割り込み（「この区画を先に調べて」「この店が違う」）は**ざっとが引き受けます** ——
  人が待っている場面なので、その場で聞ける回でないと意味がありません。
  """
  def survey_prompt do
    """
    日本の「食事処」の一覧を、**この区画ぶんだけ仕上げてください**。
    travel-log という地図アプリのスポットとして使います。

    **今回見る範囲**
    {partition}

    {current}

    **上に並んでいるのが、この範囲の全部です。** やってほしいことは 2 つで、
    **1 つめが主な仕事**です。

    **1. 足りない店を足す。** この範囲にあって、上に並んでいない店を探してください。
    名簿の元は地図辞典（Overture Maps）なので、**新しい店・小さい店・地図に
    載っていない店**は入っていません。行列のできる店、地元で名の通った店、
    その土地の名物を出す店が、まるごと抜けていることがあります。
    **手元の知識サーバー（chiezo の MCP）を先に引いてください** ——
    レート制限が無く、入っている地物は実在が確かめられています。足りなければ web で。
    **確信が持てるものだけを挙げてください。** 思い当たらなければ足さなくて構いません
    —— 既にあるものを挙げ直しても名簿は変わらず、AI の枠だけが減ります。
    **足す前に、いまも営業しているかを確かめてください。** 閉店した店の記事や
    口コミの頁は何年も残るので、見つかったことは開いている証拠になりません。
    **直近 1 年ほどの口コミ・公式の告知・営業時間の更新**のどれかで営業が確かめられた
    店だけを足し、「閉店」「閉業」「移転」の表示があるもの、確かめられなかったものは
    足さないでください（**足した閉店は、次にざっと見るの回が見つけるまで地図に残ります**）。

    **足すものには必ず座標を入れてください**（`lat` と `lon` に数で）。
    **座標の無いものはどの区画にも入らず**、次に同じ区画を見たときには
    「まだ無い」と見えるので、同じ店を何度も足すことになります。

    **2. 並んでいるものを精査する。** 座標が所在地と食い違っていれば**直し**、
    閉店したもの・食べに行く先でないものは墓標で消し（tags に
    "#{Chiezo.tombstone_tag()}" を入れ、body に理由を1行）、
    説明・ジャンル・地域・ランク・特徴の空いているところを埋めてください。
    #{closed_twin_rule()}

    #{move_by_fixing()}
    #{eat_in_rule()}
    **地域（都道府県）だけは必ず埋めてください** —— 空のままだと travel-log は
    そのスポットを地図に置けません（本文の「住所:」と座標から分かります）。
    **同じ店が 2 つに分かれていたら 1 つにまとめてください**（辞典ごとに名前の
    書き方が違うので、機械では畳めていません）。
    **逆に、1 件に別々の店が混ざっていたら分けてください。** 名簿は**見出しで
    同じものかを決めている**ので、**同じ名前の別の店が 1 件に潰れている**ことが
    あります（本文は東京の店の説明なのに座標は熊本、のように食い違って見えます）。
    見分けたら、**片方を新しい見出しで足し**（店名のうしろに市区町村を添える。
    例「東京の洋食店 (熊本市北区)」）、元の 1 件はもう片方の内容に揃えてください。
    **確かめられなかったものは触らないでください** —— 疑わしいから消す、をやると、
    正しかったものまで落ちます。
    #{merge_rule()}

    #{item_format()}

    **触ったものと足すものだけ返してください。** 触れなかったものはそのまま残ります。
    """
  end

  # 閉店した店の片割れ。**2 つの依頼文で同じ文を使う**（`move_by_fixing/0` と同じ理由）。
  # 同じ店が辞典に 2 件入っていることがあり、片方だけ消すともう片方が地図に残る
  # （実測: 閉店で消した店と同じ名前の店が、同じ住所で生きたまま残っていた）
  defp closed_twin_rule do
    """
    **閉店で消すときは、同じ店の片割れも消してください。** 同じ店が辞典に 2 件以上
    入っていることがあります（辞典違い・表記違い・見出しの後ろの「(番号)」「(町名)」だけが
    違うもの）。**上に同じ住所・同じ名前の 1 件があれば、それも同じ理由で墓標を付けて**
    ください —— 片方だけ消すと、もう片方が開いている店として地図に残ります。
    同じチェーンの別の店舗（住所が違う）は別の店なので残してください。
    """
  end

  # 座標のずれた 1 件をどう扱うか。**2 つの依頼文で同じ文を使う** ——
  # 書き分けると、片方の回だけが消し始める。実際に「本来の区画へ移動」と書いて
  # 消された店が出た（移った先の回はその店を知らないので、移動にはならない）
  defp move_by_fixing do
    """
    **座標が違うことは、消す理由ではありません。** 住所がこの範囲の外を指していても、
    **消さずに正しい緯度・経度へ直してください** —— 直せば次の回から本来の区画に並びます。
    **「本来の区画へ移す」ために消すのも同じです。** 移す手立ては座標を直すことだけで、
    消してから移すことはできません —— 移った先の回はその店を知りませんし、
    消したものには墓標が立つので、機械で作る名簿からも戻ってきません。
    **あなたが消せば、その店はそこで終わりです。**
    **tags に "#{Chiezo.locked_tag()}" が付いた店は、人が現地で確かめた位置です。
    座標を直さないでください**（直しても元の座標に戻ります）。
    """
  end

  # 食事処の線引き。**travel-log は「食べに行く先」の地図**なので、その場で
  # 食べられない店は並べない。**2 つの依頼文で同じ文を使う** —— 書き分けると、
  # 同じ店が回によって残ったり消えたりする
  defp eat_in_rule do
    """
    **その場で食べられるかで分けてください。**

    - **消す** …… 持ち帰り専門の弁当・惣菜・パン・菓子の店、百貨店の地下や駅ナカの
      物販売場、仕出し・ケータリング、入れない社員食堂。
      買って帰るだけの店は、地図に並べても行き先になりません
    - **残す** …… 席があって、その場で食べられる店。
      **持ち帰りもやっている店は残してください**（寿司屋や麺類の店の持ち帰りは、
      その店の一部です）
    - **迷ったら残す** …… 消せば名簿から消えたまま戻りません。判断の付かないものは
      触らずに置いてください
    """
  end

  # 同じ店が 2 つに分かれていたときの、どちらを採るかの決まり。
  # **2 つの依頼文で同じものを使う** —— 書き分けると、回によって別の値が残る。
  #
  # **機械で決められるところは機械で決めてある**（`extract/0` の `provides`）ので、
  # ここで言うのは**機械が畳めなかったぶん**の話。畳めていれば AI は 1 件しか見ない
  defp merge_rule do
    """
    **まとめるときは、出典のタグを見て決めてください。**

    - **座標は "#{@source_tags[:osm]}" の付いた側**を残す（現地を歩いた人が置いた点です）。
      無ければ "#{@source_tags[:wikipedia]}"、それも無ければ残ったほうで構いません
    - **説明は "#{@source_tags[:wikipedia]}" の付いた側**を残す（読み物になっているのはこちらです）
    - **電話・公式サイトは埋まっているほう**を残す
    - **出典のタグは、まとめた側にすべて残してください**（どの辞典に載っていた店かは、
      次に見るときの手がかりになります）
    """
  end

  # 1 件の形。**2 つの依頼文で同じものを使う** —— 書き分けると、片方だけ直したときに
  # 回によって別の形が返ってくる（travel-log が読むのはこの形）
  defp item_format do
    """
    1 件の形は次のとおりです。

    - title: **店の名前だけ**（地名や説明を混ぜない）。
      **同じ店は同じ表記で返してください** —— ここが同一の鍵で、変えると別の店として
      増えます。上に並んでいるものを直すときは、その表記のまま返してください
    - body: 1 行目に「所在地: 都道府県 市区町村 まで」、2 行目以降に
      **2〜3 文の紹介**（何が名物で、どういうときに寄る店か）。
      味の評価ではなく、**行くかどうかを決められること**を書いてください
    - url: 出典（店の公式サイトか、それに準ずるもの）
    - lat / lon: 緯度・経度を数で。**直すときと足すときだけ**書きます
    - tags: **いま付いているタグは、直すもの以外そのまま残してください**
      （返した内容で丸ごと置き換わるので、書かなかったタグは消えます）
      - "#{kind_tag()}" —— この一覧の目印。**必ず残してください**
      - "#{genre_tag()}:<ラーメン / 寿司 / 和食 のような料理の種類>"。
        **先頭のものが地図の見た目になる**ので、その店を一言で言うものを先に。
        当てはまるものが複数あれば並べて構いません
      - "#{area_tag()}:<東京都 / 京都府 のような都道府県>"。
        **空いているものは必ず埋めてください** —— travel-log の `region` に当たり、
        ここが無いスポットは地図に置けません。名簿の元の店舗辞典は、日本では
        この欄がほとんど空のまま入ってきます
      - "#{feature_tag()}:<特徴>" —— **その店の特徴**。travel-log の絞り込みになります。
        **次の語から選んでください**（新しい語は作らない）:
        #{Enum.join(@features, " / ")}。
        **調べて確かめられたものだけ**付けてください —— 付いていないことは
        「分からない」の意味で、付けた印は「そうだ」と読まれます
      - "#{rank_tag()}:<A〜E>" —— **どれくらい知られているか**。
        A=全国から人が来る、B=その県を代表する、C=その市区町村で知られる、
        D=地元で親しまれている、E=それ以外。**地図の丸の大きさになります**ので、
        迷ったら下の段にしてください（全部が A だと、大きさが何も表さなくなります）
      - "#{Enum.join(source_tags(), ~s(" / "))}" —— **どの辞典から来たか**。
        機械が付けたものなので、**足したり消したりしないでください**
        （自分で見つけて足した 1 件には、どれも付けません）

    **消す 1 件は、形が 1 つ違います。**

    - tags に "#{Chiezo.tombstone_tag()}" を入れる
    - **body に消す理由を 1 行**書く（「◯年に閉店」「◯◯と同じ店なのでまとめた」
      「弁当屋で食べに行く先ではない」のように、**何をどう判断したか**）

    **理由の無い墓標は、あとから誰にも直せません。** 消したものは名前が並ぶだけで、
    本文は機械が入れた元のまま残ります —— **消し間違いに気づけず、戻す判断もできません**
    （実際に、座標が違うだけの店がまとめて消え、理由が無いために戻せませんでした）。
    **1 行で構いません。**
    """
  end
end
