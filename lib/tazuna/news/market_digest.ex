defmodule Tazuna.News.MarketDigest do
  @moduledoc """
  市況ニュースのまとめの書き方。**売買提案の AI が読む形を先に決め、人はそれをそのまま読みます**。

  売買提案のアプリ は Chiezo の `tazuna_market` から最新のまとめを 1 本取り、市況サマリーとして
  売買提案の AI に渡します。既定のまとめ（`Tazuna.News.digest_prompt/1` の既定の書き方）は
  人が読むレポートで、章立ての解説や「なぜ押さえるべきか」の論評、表や強調が入ります ——
  売買の判断に要るのは、**いつの・何の値が・どう動いたか**と、**どの銘柄にどんな材料が出たか**で、
  論評は AI が自分で組み立てるものです。

  **AI 用と人間用を別々に書かせません。** 2 本にすると、AI に何が伝わったのかを人が
  確かめられなくなります。決まった節に事実を並べた 1 本を、画面ではそのまま描きます
  （`Tazuna.News.Report` が読める記法だけを使います）。

  **材料は直近 24 時間です**（`{recent:24h}`）。前回からの差分（`{recent}`）にすると、
  回す間隔がそのまま幅になります —— 1 日 2 回まとめると 12 時間ぶんしか入らず、
  最新の 1 本だけを読む 売買提案のアプリ には半日ぶんしか届きません。窓が重なる回どうしは同じものを
  読み直しますが、それが目的です（毎回、丸 1 日ぶんをまとめ直す）。
  """

  @doc "まとめる回の頭の一文。"
  def intro do
    "直近 24 時間に入った市況ニュースを、**売買判断の材料として読む要約 1 件**にしてください。"
  end

  @doc "材料（直近 24 時間。Chiezo が置き換える）。"
  def material do
    """
    材料は次のとおりです。**これより前のことと、ここに書かれていないことは書かないでください**
    （覚えている知識で補うと、古い出来事や別の年の数字が最新の材料として伝わります）。
    {recent:24h}
    """
  end

  @doc "body の書き方（`Tazuna.News.digest_prompt/1` の既定の書き方の代わり）。"
  def format do
    """
    - body: 下の形で書いてください。**読むのは売買提案を書く AI** で、人はこれをそのまま
      画面で読み、AI に何が伝わっているかを確かめます。**解説・感想・見通しは書かず、
      事実を、日付と数字と銘柄コードつきで**並べてください

    body の形です。**節の見出しと順番はこのとおりに**してください（読む側は節の名前で探します）。
    使ってよい記法はここにあるものだけで、表・強調（`**`）・HTML・画像は使わないでください。

    ```
    ## 要旨
    <その 24 時間を一言で。1 文>

    ・<要点を 1 行で>
    出典: [記事の見出し](URL)
    ・<要点を 1 行で>
    出典: [記事の見出し](URL)
    ・<要点を 1 行で>
    出典: [記事の見出し](URL)

    ## 相場の数字
    - <指標>: <値>（<日付と時点。例 10/2 終値>）<前日比があれば>（[記事の見出し](URL)）

    ## マクロ・政策
    - <M/D> <事実を 1 つ>（[記事の見出し](URL)）

    ## 業種・テーマ
    - <業種>: <M/D> <事実を 1 つ>（[記事の見出し](URL)）

    ## 個別銘柄
    - <証券コード> <会社名>: <M/D> <材料を 1 つ>（[記事の見出し](URL)）

    ## これからの予定
    - <M/D> <予定（指標の発表・会合・決算・休場など）>（[記事の見出し](URL)）

    ## 未確認・食い違い
    - <報道どうしで食い違う点・続報待ちのもの>（[記事の見出し](URL)）
    ```

    **「## 要旨」は通知にそのまま流れます。**
    - **1 行目だけで意味が通るように**書いてください（通知は畳まれて先頭しか見えないことがあります）
    - 続けて**空行を 1 つ**置き、要点を「・」で **3〜4 行**。**1 行に 1 つのこと**だけ
    - **要点ごとに、すぐ下の行へ根拠にした記事を `出典: [記事の見出し](URL)` で 1 行**
    - 飾りの記号（`**` や行頭の `-`）は入れないでください（通知は Markdown として描かれません）

    節の書き方です。
    - **1 行に 1 つの事実**。同じ出来事を報じた記事が複数あれば 1 行にまとめ、出典は 1 本にしてください
    - **日付を必ず付けてください**（`M/D`。時刻が分かれば `10/2 終値` `10/3 朝` のように）。
      いつの話か分からない事実は、読む側が古いものと区別できません
    - **数字は上に書かれている値をそのまま**写してください（丸めない・計算しない・推測しない）
    - 証券コードは、その記事のタグ「銘柄:<コード>」にあるものだけを使ってください。
      無ければコードを書かずに会社名だけにします（**コードを推測しない**）
    - 個別銘柄は、決算・業績修正・M&A・大型の受注や提携・不祥事・行政処分など、
      **株価に効く材料が出たもの**を優先し、重要度の高いものから並べてください
    - 「相場の数字」には、日経平均・TOPIX・為替・金利・米国株・原油など、上に値が書かれているものだけ
    - **当てはまるものが無い節も消さずに `- なし` と書いてください** —— 節が無いと、
      読む側には「無かった」のか「書き忘れた」のかが区別できません
    - 各行の出典は `（[記事の見出し](URL)）` で 1 本。**見出しも URL も、上に並んでいる
      ものをそのまま写してください**（上に無い URL を作らない）
    - 重要度が低いもの・株価に関係の薄いものは入れなくて構いません
    """
  end
end
