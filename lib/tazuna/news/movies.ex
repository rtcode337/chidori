defmodule Tazuna.News.Movies do
  @moduledoc """
  映画の話題の**1 件 = 1 作品**の作り方。記事を溜めず、作品ごとに公開日・注目度・
  口コミを育てます（`Tazuna.Topics` の `works`）。

  ## 記事を溜めない理由

  映画の配信元（映画のニュースサイト）を溜めると、1 本の作品について記事が何本も
  並び、**公開日も注目度も口コミも作品ごとにまとまりません**。知りたいのは
  「いつ何が公開されて、どれが注目されていて、観た人の反応はどうか」なので、
  1 件を作品にして、情報はその 1 件に書き足していきます。

  ## 巡回

  - 情報収集（1 日に 1 回）—— **いま公開中の作品**と、これから公開される作品を外から
    探して足す。**1 回に探すのは 1 区切りだけ**（`segments/0` を順に回る）。**足すだけ**
  - 整理（1 日に 1 回）—— 公開日と注目度を付け直し、公開された注目作に口コミと
    興行成績を書き足し、公開から時間が経ったものを落とす

  ## タグ

  カレンダーは技術イベントと同じ仕組み（`Tazuna.News.Events`）で、日付のタグの名前だけが
  違います（`公開日:`）。注目度のタグは同じもの（`注目度:高/中/低`）を使います。
  """

  alias Tazuna.News.Events

  @date_tag "公開日"
  @stream_tag "配信開始"
  @format_tag "上映形式"
  @review_tag "口コミ"

  # 先を探す月数。**日本の公開日は 2〜3 か月前には決まっている**ことが多く、
  # それより先は「公開予定」だけで日付が無い（カレンダーに出せない）
  @look_ahead_months 3

  # 公開から何日経ったら落とすか。**上映はおおむね 1〜2 か月で終わる**。
  # 残すと、カレンダーの過去の月と注目作の一覧が観られないもので埋まる
  @keep_after_release_days 60

  # 口コミを書き直す間隔（日）。**公開直後は評判が動く**ので、同じ作品でも
  # 間を空けて取り直させる。毎日書き直させると、同じ作品に枠を使い続ける
  @review_refresh_days 7

  # 探す回が順に回る区切り。**1 回に探すのは 1 つだけ**です —— 日本の劇場公開は
  # 週に 20 本を超え、公開中と 3 か月先までを合わせると数百本になる。AI が 1 回で
  # 返せるのは数十件なので、全部を 1 回で頼むと最初の 1〜2 か月で打ち切られる。
  # **次の区切りは AI に返させて Chiezo のカーソルに覚えさせる**（`{cursor}`）。
  # 月は今日から数えた呼び名で持つ（日付で持つと、月が替わった日に区切りが消える）
  @segments ["公開中", "今月", "来月", "再来月", "3か月先"]

  # 探す回の間隔（分）。**1 日に 1 回**で、区切りを一周するのに 5 日かかる ——
  # 同じ区切りを探し直すまでの間に決まった公開日は、次の周で入る
  @survey_minutes 24 * 60

  # 整えるのは 1 日に 1 回。口コミも注目度も、半日で入れ替わる話ではない
  @refine_minutes 24 * 60

  @doc "公開日のタグの頭（カレンダーはこのタグで引く）。"
  def date_tag, do: @date_tag

  @doc "配信開始のタグの頭。"
  def stream_tag, do: @stream_tag

  @doc "上映形式のタグの頭。"
  def format_tag, do: @format_tag

  @doc "探す回が順に回る区切り（この順で回り、最後の次は最初に戻る）。"
  def segments, do: @segments

  @doc "先を探す回の間隔（分）。"
  def survey_minutes, do: @survey_minutes

  @doc "整理の回の間隔（分）。"
  def refine_minutes, do: @refine_minutes

  @doc """
  作品に付けるタグの決まり。**先を探す回と整理の回で同じ文を使う** ——
  書き分けると、回によって付く印の揃い方が変わり、カレンダーの目立たせ方がぶれる。
  """
  def tag_rules do
    """
    - "#{@date_tag}:<YYYY-MM-DD>" —— **日本での劇場公開の初日を必ず 1 つ**。
      先行上映ではなく全国公開の日。地域ごとに順次公開なら最初の日
    - "#{Events.attention_tag()}:高" / "#{Events.attention_tag()}:中" / "#{Events.attention_tag()}:低" を**必ず 1 つ** ——
      **どれだけ注目されているか**です。カレンダーで目立たせるのに使います。
      - 高: 大作・話題作。人気シリーズの新作、評価の高い監督や俳優の作品、
        海外で大ヒットした作品や主要な映画賞を取った作品、公開後に興行ランキングの上位にいるもの
      - 中: 名の通った作品だが、そこまで話題になっていないもの
      - 低: 公開規模の小さい作品
      **迷ったら低に**（全部が高だと、目立たせる意味がなくなります）
    - "#{@format_tag}:<形式>" —— IMAX・Dolby Cinema・4DX など、**決まっているものだけ**（無ければ付けない）
    - "#{@stream_tag}:<YYYY-MM-DD>" —— 配信の開始日が**決まっていれば**（無ければ付けない）
    - ジャンル（アニメ・邦画・洋画・アクション・ホラー など、当てはまるもの）
    """
    |> String.trim_trailing()
  end

  @doc """
  探して足す回の依頼文（巡回「情報収集」）。**いま公開中の作品と、これから公開される
  作品を、1 回に 1 区切りずつ探させます**（`segments/0`。今回の区切りは `{cursor}`）。

  **対象を絞ります**（全国規模で公開されるものと、小規模でも話題のもの）。1 館だけの
  上映まで入れると数百本になり、1 区切りでも探しきれないうえ、カレンダーでは
  注目度の低いものとして件数に畳まれるだけです。

  **公開中のものも探させます。** 技術イベントと違い、映画は公開されてからが
  本番です（口コミで観るかを決める）—— 未来だけを探すと、始めたときに公開中の
  作品が 1 本も入らず、公開済みの作品は後から見つけても足されません。

  **いま入っているものの見出しを見せます**（`{names}`）。見せないと、同じ作品を
  回ごとに言い回しを変えて足し直します。**公開日が決まったものだけ**足させます
  （決まっていないものはカレンダーに出ない）。**劇場公開作だけ**（配信だけの作品は
  入れない）。
  """
  def survey_prompt(interest) do
    """
    **日本の映画館でいま公開中の映画と、これから公開される映画**を探して足してください。
    今日は {now} です。

    **今回探すのは「{cursor}」の区切りだけです。** 区切りは次の順に回ります
    （1 回に全部を探すと途中で打ち切られるので、分けて探しています）。
    #{segment_lines()}

    区切りが上のどれでもないとき（初めての回など）は「#{hd(@segments)}」を探してください。
    **next_cursor には、今回の次の区切りの名前**（#{Enum.join(@segments, " → ")} → #{hd(@segments)} の順）を
    そのまま入れてください。

    何を集めるかは次のとおりです。
    #{interest}

    **対象は、全国規模で公開される作品と、小規模でも話題になっている作品**です
    （1〜数館だけで上映する作品は、話題になっていなければ入れない）。
    公開予定の一覧（映画の情報サイトの公開スケジュール、配給会社の発表）や、
    公開中なら興行ランキングを当たると漏れが減ります。**その区切りの中は、漏れなく**探してください。

    - **劇場で公開されるものだけ**です。配信だけの作品は入れないでください
    - **公開日が決まっているものだけ**足してください（「近日公開」「来春」はまだ入れない）
    - 再上映・リバイバルは、話題になっているものだけ

    いま入っているものは次のとおりです（見出しとタグ）。
    {names}

    **上に並んでいる作品は足さないでください。** 見出しの書き方が違っても、
    同じ作品は同じ 1 件です。**確信が持てるものだけ**を挙げてください。

    1 件ごとに次の形で返してください。
    - title: 日本での題名（邦題）。**シリーズの何作目かが分かるように**（副題まで）
    - body: 次の形で。**結末や仕掛けは書かないでください**（読む人はまだ観ていません）
        どんな作品か: 1〜2 文（監督・主な出演者・原作があれば）
        注目の理由: 1 文（注目度が中以上のとき。なぜ注目されているか）
    - url: 公式サイト（**必ず入れる**。無ければ作品の情報ページ）
    - tags: 次のとおり

    #{tag_rules()}
    """
  end

  # 区切りごとの説明（依頼文に並べる）
  defp segment_lines do
    Enum.map_join(@segments, "\n", fn
      "公開中" ->
        "- 公開中 —— 日本での公開から #{@keep_after_release_days} 日以内で、まだ上映しているもの"

      "今月" ->
        "- 今月 —— 今日から今月末までに公開されるもの"

      "来月" ->
        "- 来月 —— 来月に公開されるもの"

      "再来月" ->
        "- 再来月 —— 再来月に公開されるもの"

      "3か月先" ->
        "- 3か月先 —— 今月から数えて #{@look_ahead_months} か月先の月に公開されるもの"
    end)
  end

  @doc """
  整理の回の依頼文。**今ある作品を全部見せて**（`{current}`）、公開日と注目度を
  付け直し、公開された注目作に口コミと興行成績を書き足し、要らないものを落とします。

  **口コミは注目度が高い作品だけ**です。全部に書かせると、1 回で数十本の評判を
  外に当たりに行くことになり、枠を食うわりに読まれません。**書いた日をタグに
  残させます**（`口コミ:<日付>`）—— 残さないと、同じ作品の評判を毎日取り直します。
  """
  def refine_prompt(interest) do
    """
    いま入っている映画を見直して、**印を付け直し、注目作に口コミを書き足し、
    要らないものを落としてください**。今日は {now} です。

    何を大事とみなすかは次のとおりです。
    #{interest}

    いま入っているものは次のとおりです。
    {current}

    **1. 公開日と注目度を付け直す。**
    公開日が変わった（延期・前倒し）ものは直してください。注目度は、公開が近づいて
    話題になったもの・公開後に興行が伸びたものは上げ、期待ほどでなかったものは下げてください。

    **2. 公開された注目作に、口コミと興行成績を書き足す。**
    "#{Events.attention_tag()}:高" の作品のうち、**日本で公開されたもの**（公開日が今日以前）が対象です。
    まだ "#{@review_tag}:" のタグが無いもの、または付いている日付から #{@review_refresh_days} 日以上
    経ったもの（公開から 1 か月以内のものだけ）を当たってください。
    - body の末尾に次の形で足す（前に書いたものがあれば置き換える）
        口コミ（<M月D日>時点）: 観た人の反応の傾向を 2〜3 文。**自分の言葉で**
          （「映像を評価する声が多い」「後半の展開で賛否が割れている」）
        興行（<M月D日>時点）: 分かれば、動員・興行収入・ランキングの順位
        出どころ: 当たったページの URL（1〜3 本）
    - tags に "#{@review_tag}:<YYYY-MM-DD>"（書いた日）を足す（前の日付は外す）
    - **口コミの本文は写さないでください**（転載になるうえ、1 人の感想は作品の評判ではありません）
    - **結末や仕掛けは書かないでください**（読む人はまだ観ていません）
    - 海外で先に公開されている注目作は、日本公開の前でも海外の評判を
      「口コミ（海外）」として書いて構いません

    **3. 要らないものを落とす。**
    次のものは **tags に "#{Tazuna.Chiezo.tombstone_tag()}" だけを入れて返してください**（墓標）。
    **そのとき body に、なぜ消すのかを 1 行で書いてください**。
    - 日本での公開日から #{@keep_after_release_days} 日以上経ったもの
    - 劇場公開をしないと分かったもの（配信だけになったもの）、公開が中止になったもの
    - 同じ作品の 1 件が既にあるもの（**残すほうは 1 つだけ**。先に入っているほうを残す）

    **返すのは、触ったものと落とすものだけ**です。触らなかったものはそのまま残ります。
    **返すときは、title は今のまま、tags は全部**（変えないものも）返してください ——
    返した tags がそのまま付け替わります。body を変えないなら body は返さなくて構いません。
    **next_cursor は返さないでください**（情報収集の回が、次に探す区切りを覚えている印です）。

    タグの決まりは次のとおりです。

    #{tag_rules()}
    - "#{@review_tag}:<YYYY-MM-DD>" —— 口コミを書いた日（書いたものだけ）
    """
  end

  @doc """
  作品の説明を、画面に出す形にします（口コミまで全部出す）。

  技術イベントの説明は頭だけで切りますが、作品は**口コミが本文の末尾にある**ので、
  切ると一番見たいところが落ちます。整理の回に短く書かせているので、そのまま出します。
  """
  def body_lines(%{summary: summary}) when is_binary(summary) do
    summary
    |> String.split("\n")
    |> Enum.map(&String.trim/1)
    |> Enum.reject(&(&1 == ""))
  end

  def body_lines(_entry), do: []

  @doc "上映形式（タグから。無ければ空）。"
  def formats(%{tags: tags}), do: values(tags, @format_tag)
  def formats(_entry), do: []

  @doc "配信開始日（タグから。無ければ nil）。"
  def streaming(%{tags: tags}) do
    Enum.find_value(values(tags, @stream_tag), fn value ->
      case Date.from_iso8601(value) do
        {:ok, date} -> date
        _ -> nil
      end
    end)
  end

  def streaming(_entry), do: nil

  @doc "口コミを書いた日（タグから。まだなら nil）。"
  def reviewed_on(%{tags: tags}) do
    Enum.find_value(values(tags, @review_tag), fn value ->
      case Date.from_iso8601(value) do
        {:ok, date} -> date
        _ -> nil
      end
    end)
  end

  def reviewed_on(_entry), do: nil

  defp values(tags, head) do
    for tag <- tags,
        String.starts_with?(tag, head <> ":"),
        value = tag |> String.replace_prefix(head <> ":", "") |> String.trim(),
        value != "",
        do: value
  end
end
