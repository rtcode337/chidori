defmodule Tazuna.News.ComedyEvents do
  @moduledoc """
  お笑いのイベントの集め方（`Tazuna.Topics` の `look_ahead`）。**カレンダーは技術イベントと
  同じ仕組み**（`Tazuna.News.Events`。開催日・開催地・注目度のタグで引く）で、
  違うのは何を探すかと、注目度の物差しだけです。

  ## テレビ番組も 1 件のイベント

  賞レースの決勝や大型の特番は、会場ではなく**放送で観るもの**です。開催地は
  `開催地:テレビ` / `開催地:配信` と書かせ、カレンダーは放送日で並べます
  （決勝が生放送なら、開催日と放送日は同じ 1 件）。

  ## 配信元は持たない

  技術イベントの connpass のような、お笑いのイベントを機械で配っている先が無いので、
  **月ごとに外を探す回（情報収集）だけで回します**。終わったものを消す・タグを揃えるのも
  その回の仕事です（`housekeeping/0`）—— 整理の回を別に置いていた頃は、整理の「上に無い
  ものを探して足す」が情報収集と重なり、AI の回が 1 日 2 回になっていた。
  単独ライブは数が多いので、名の通った芸人のもの（ツアーや大きな会場）に絞らせます。
  """

  alias Tazuna.News.Events

  # 種類のタグの頭（賞レース・特番・ライブ・単独ライブ）
  @kind_tag "種類"
  # 出演者のタグの頭。**芸能人の関連図とつなぐため**、名前は Wikipedia の見出しの書き方で
  @cast_tag "出演"

  # 先を探す月数。賞レースの決勝や大型の特番は 2〜3 か月前には日程が出る
  @look_ahead_months 3

  # 先を探す回が順に回る区切り（月）。**1 回に探すのは 1 つだけ**（技術イベントと同じ理由）
  @segments ["今月", "来月"] ++ Enum.map(2..@look_ahead_months, &"#{&1}か月先")

  # 先を探す回の間隔（分）。1 日に 1 回で、区切りを一周するのに 4 日
  @look_ahead_minutes 24 * 60

  @doc "種類のタグの頭。"
  def kind_tag, do: @kind_tag

  @doc "出演者のタグの頭。"
  def cast_tag, do: @cast_tag

  @doc "先を探す回の間隔（分）。"
  def look_ahead_minutes, do: @look_ahead_minutes

  @doc "先を探す回が順に回る区切り（この順で回り、最後の次は最初に戻る）。"
  def segments, do: @segments

  @doc """
  開催日・開催地・種類・注目度・出演者のタグの決まり。**整理の回と先を探す回で同じ文を
  使う**（書き分けると、回によって付く印の揃い方が変わる）。
  """
  def tag_rules do
    attention = Events.attention_tag()

    """
    - "#{Events.date_tag()}:<YYYY-MM-DD>" —— **開催日（初日）を必ず 1 つ**。日本時間の日付で。
      テレビ番組なら**放送日**（決勝の生放送なら、決勝の日）
    - "終了日:<YYYY-MM-DD>" —— **連日のとき・ツアーのときだけ**、最終日を
    - "#{Events.place_tag()}:<都道府県>" / "#{Events.place_tag()}:テレビ" / "#{Events.place_tag()}:配信" ——
      **必ず**。会場のある都道府県を「東京都」「大阪府」の形で。テレビ番組なら
      "#{Events.place_tag()}:テレビ"、配信だけなら "#{Events.place_tag()}:配信"、会場と放送の両方なら両方。
      ツアーは主な会場の都道府県を 3 つまで
    - "#{@kind_tag}:賞レース" / "#{@kind_tag}:特番" / "#{@kind_tag}:ライブ" / "#{@kind_tag}:単独ライブ" を**必ず 1 つ** ——
      賞レースは予選・準決勝・決勝とその放送、特番は賞レース以外のお笑いの大型番組、
      ライブは事務所や劇場の大型公演・フェス、単独ライブは芸人ごとの単独公演とツアー
    - "#{@cast_tag}:<芸人の名前>" —— **主な出演者を 5 組まで**。コンビ・トリオは**コンビ名で**、
      ピン芸人は芸名で、**Wikipedia の記事の見出しと同じ書き方**で（「(お笑いコンビ)」のような
      括弧書きは付けない）。賞レースの予選のように出演者が決まっていなければ付けない
    - "#{attention}:高" / "#{attention}:中" / "#{attention}:低" を**必ず 1 つ** ——
      **どれだけ注目されているか**です。カレンダーで目立たせるのに使います。
      - 高: M-1グランプリ・キングオブコント・R-1グランプリ・THE W・THE SECOND などの
        決勝と準決勝、年末年始の大型のお笑い特番、人気芸人の大きな会場の単独ライブやツアー
      - 中: 賞レースの準々決勝、名の通った芸人の単独ライブ、事務所や劇場の大型公演・フェス
      - 低: 小さな会場の公演、賞レースの 1 回戦・2 回戦
      **迷ったら低に**（全部が高だと、目立たせる意味がなくなります）
    """
    |> String.trim_trailing()
  end

  @doc """
  先を探す回に足す、**今あるものの片付け**（整理の回を置かないので、この回が引き受ける）。
  上に見出しとタグが並んでいるので、本文を見なくても終わったものとタグの欠けは分かる。
  """
  def housekeeping do
    """
    **探し終えたら、上に並んでいるものも片付けてください。**

    - **終わったイベント**（開催日・放送日が今日より前で、終了日も過ぎたもの）は墓標で消してください
      （tags に "#{Tazuna.Chiezo.tombstone_tag()}" を入れ、body に消す理由を 1 行）
    - **延期・中止**が分かったものは、日付を直すか墓標で消してください
    - **タグが欠けているもの**（開催日・開催地・種類・注目度）は、上の決まりどおりに足して
      返してください。**いま付いているタグはすべて残したうえで**足す（返したタグで丸ごと
      置き換わります。body は返さなければ今のまま残ります）
    - 触らないものは返さなくて構いません
    """
  end

  @doc """
  先を探す回の依頼文（巡回「情報収集」）。**1 回に 1 か月ずつ**探させます
  （今回の月は `{cursor}`）。いま入っているものの見出しを見せます（`{names}`）——
  見せないと、同じイベントを回ごとに言い回しを変えて足し直します。
  """
  def look_ahead_prompt(interest, _interests \\ []) do
    """
    これから開かれるお笑いのイベントと、お笑いのテレビ番組のうち、**今日から
    #{@look_ahead_months} か月先までのもの**を探して足してください。今日は {now} です。

    **今回探すのは「{cursor}」に開かれる・放送されるものだけです**（今日から数えた月。
    「今月」は今日から今月末まで）。月は次の順に回ります —— 1 回に全部の月を探すと途中で
    打ち切られるので、分けて探しています。
    #{Enum.join(@segments, " → ")} → #{hd(@segments)}

    月が上のどれでもないとき（初めての回など）は「#{hd(@segments)}」を探してください。
    **next_cursor には、今回の次の月の名前**を上の書き方のまま入れてください。

    何を集めるかは次のとおりです。
    #{interest}

    探してほしいのは次のものです。

    - 賞レース（M-1グランプリ・キングオブコント・R-1グランプリ・THE W・THE SECOND など）の
      予選・準決勝・決勝と、その放送
    - お笑いの大型の特番（年末年始の特番、ネタ番組の大型版など）
    - 事務所や劇場の大型公演・お笑いのフェス
    - 芸人の単独ライブとツアー（**名の通った芸人のもの**。小さな会場の公演は、
      話題になっているものだけ）

    賞レースの公式サイト、テレビ局の番組表、芸能事務所・劇場の公演情報、チケットの
    販売サイトを当たると漏れが減ります。**その月の中は、漏れなく**探してください。

    いま入っているものは次のとおりです（見出しとタグ）。
    {names}

    **上に並んでいるイベントは足さないでください。** 見出しの書き方が違っても、
    同じイベントの同じ回は同じ 1 件です。**開催日（放送日）が決まっているものだけ**
    足してください（未定のものはカレンダーに出ません）。**確信が持てるものだけ**を
    挙げてください。

    1 件ごとに次の形で返してください。
    - title: イベントの名前。**年や回を入れてください**（「M-1グランプリ2026 決勝」のように。
      同じイベントの別の回は別の 1 件です）
    - body: 1〜2 行。どんなイベントか（会場か放送局、主な出演者）。チケットの発売日が
      分かれば 1 行
    - url: 公式サイトかチケットの申込ページ（**必ず入れる**。テレビ番組なら番組の公式サイト）
    - image: イベントの画像の URL（公式サイトのページの og:image。
      **ページではなく画像そのものの URL**。分からなければ入れない）
    - tags: 次のとおり

    #{tag_rules()}
    """
  end
end
