  要らなくなります）。

  **終わったら要らなくなるもの**は別で、そこは日付では落とせません ——
  半年先のイベントを 30 日の期限で落とすと、いちばん要るときに消えます。
  そういう話題は期限を持たず、終わったものを整理の回に落とさせます。
