defmodule Tazuna.SweepNames do
  @moduledoc """
  Chiezo に置く巡回の名前。**収集を足すときは、ここから選びます**（新しい名前を作らない）。

  名前は画面にも Chiezo の変更履歴にも出るので、収集ごとに別の呼び方をすると、
  同じ仕事をしている回なのかが読めなくなります（「拾う」「読む」「整える」が
  それぞれ「機械収集」「整理」と同じ仕事だったのに、別の名前で並んでいた）。
  **仕事が同じなら同じ名前**にし、どうしても当てはまらない仕事が出たときだけ
  ここへ足します。

  | 名前 | 仕事 |
  | --- | --- |
  | 機械収集 | AI を呼ばずに機械で拾う（配信元の RSS・辞典からの抽出・タグの数え上げ） |
  | 集める | 配信元を持たない収集で、AI に外から集めさせる |
  | ざっと見る | 区画を一周して、座標・閉店・空欄を手早く直す |
  | 整理 | 入ったものを読んで、印を付け直し・要らないものを落とし・足りないものを足す（範囲ごとの食事処は区画ごとに 1 件ずつ確かめてから足す） |
  | 情報収集 | 足りないものを外から探して足す（食事処は区画ごとに、tazuna が起点と時刻を決めて起こす。技術イベントは先の月を週に 1 回） |
  | 要約 | 前回から入ったものを 1 件の読み物にまとめる |
  | 興味の要約 | 要約と同じ仕事を、興味トピックに絞って別の 1 本で |
  """

  @doc "AI を呼ばずに機械で拾う回。"
  def machine, do: "機械収集"

  @doc "配信元を持たない収集で、AI に集めさせる回。"
  def collect, do: "集める"

  @doc "区画を一周して手早く直す回。"
  def scan, do: "ざっと見る"

  @doc "入ったものを読んで印を付け直し、落とし、足す回。"
  def tidy, do: "整理"

  @doc """
  整理の回の間隔（分）。**どの収集でも同じ**にそろえる。設定ページから変えられる
  （`Tazuna.CollectPace`。既定は 12 時間）。

  収集ごとに 4 時間・12 時間・1 日と散らばっていた頃は、ワーカーの待ち行列が
  溜まってきたときに、何がどれだけ積まれるのかが読めなかった（しかも短い間隔の
  収集ほど枠を食う）。まとめの直前にはもう 1 回起こすので（`Tazuna.Digest`）、
  要約の材料が古くなることはない。

  **6 時間ごとでは枠の回復が追いつかなかった。** 整理はほぼ 1 つの相手（codex）が
  引き受けていて、その 7 日枠を 1 日約 29% のペースで使っていた（7 日で釣り合うのは
  1 日約 14%）。整理がその 4 分の 3 を占めていたので、既定を 12 時間にした。
  AI が目を通すまで画面に出ない収集（ニュース類）は、そのぶん遅れて出る。

  **実行時に読む**（コンパイル時の定数にしない）—— 画面で変えた値が効かなくなる。
  """
  def tidy_minutes, do: Tazuna.CollectPace.minutes(:tidy)

  @doc """
  ざっと見るの回の間隔（分）。関連図と食事処で同じ。設定ページから変えられる
  （`Tazuna.CollectPace`。既定は 2 時間）。
  """
  def scan_minutes, do: Tazuna.CollectPace.minutes(:scan)

  @doc "足りないものを外から探して足す回。"
  def survey, do: "情報収集"

  @doc "まとめを書く回。"
  def digest, do: "要約"

  @doc "興味トピックに絞ったまとめを書く回。"
  def interest_digest, do: "興味の要約"

  @doc "ここにある名前の全部（テストが、定義がここから選んでいるかを見る）。"
  def all, do: [machine(), collect(), scan(), tidy(), survey(), digest(), interest_digest()]
end
